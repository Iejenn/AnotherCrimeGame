// Writes supabase/migrations/0013_new_city.sql from the map (src/street/map.ts), so the server's copy of the map
// (size, spawn, shop areas, the guard's route, the pigeon tiles, the crime spots) can't disagree with the game.
// Run: npx vite-node scripts/map-sql.ts
import { writeFileSync } from 'node:fs';
import { H, NODES, SPAWN, STORE, W, WEAPONS } from '../src/street/map';
import { GUARD_ROUTE } from '../src/game/watchers';
import { PIGEON_TILES } from '../src/game/enemies';

/** A live-definition replace: take the function as it is on the server, swap exact text, fail if it's not there. */
const swap = (fn: string, pairs: [string, string][]) => {
  const q = (t: string) => `'${t.replace(/'/g, "''")}'`;
  return `do $do$
declare def text;
begin
  def := pg_get_functiondef('${fn}'::regprocedure);
${pairs.map(([a, b]) => `  if position(${q(a)} in def) = 0 then raise exception '${fn}: anchor not found: %', ${q(a)}; end if;
  def := replace(def, ${q(a)}, ${q(b)});`).join('\n')}
  execute def;
end $do$;`;
};
/** The same with regular expressions (for the long tile lists). */
const swapRe = (fn: string, pairs: [string, string][]) => `do $do$
declare def text;
begin
  def := pg_get_functiondef('${fn}'::regprocedure);
${pairs.map(([a, b]) => `  if def !~ '${a}' then raise exception '${fn}: pattern not found: %', '${a}'; end if;
  def := regexp_replace(def, '${a}', '${b}');`).join('\n')}
  execute def;
end $do$;`;

const [sx, sy] = SPAWN;
const spots = NODES.map((n) => {
  const w = n.wanders;
  return `  ('${n.id}', ${n.x}, ${n.y}, ${w ? `${w.x0}, ${w.y0}, ${w.x1}, ${w.y1}` : 'null::int, null::int, null::int, null::int'})`;
});

const sql = `-- 0013: the new city (docs/design.md §7): 3×3 blocks of 4 lots each, with 7-tile streets (road + sidewalks)
-- between them. The map is ${W}×${H} tiles now (was 44×37). GENERATED by scripts/map-sql.ts from src/street/map.ts.
--
-- What changes on the server:
--  - map edges, spawn point, Eddy's and Ray's areas, the guard's route and the pigeon tiles inside the functions
--    that use them (each swapped in its live definition; the migration stops if a piece isn't found);
--  - the crime spots move to their new places (same ids);
--  - DATA RESET (the old positions don't exist in the new city): everyone's position goes back to the spawn
--    (null = spawn), attempts in progress and fights stop, graves move next to the spawn (with what's in them),
--    walking routes are cleared. Nobody loses cash, items or XP.

-- ---------- map edges and spawn ----------
${swap('game.can_reach(public.players, integer, integer)', [
  ['x between 0 and 43 and y between 0 and 36', `x between 0 and ${W - 1} and y between 0 and ${H - 1}`],
  ['coalesce(p.pos_x, 18)', `coalesce(p.pos_x, ${sx})`],
  ['coalesce(p.pos_y, 22)', `coalesce(p.pos_y, ${sy})`],
])}
${swap('public.walk(integer, integer, jsonb)', [['sx not between 0 and 43 or sy not between 0 and 36', `sx not between 0 and ${W - 1} or sy not between 0 and ${H - 1}`]])}
${swap('game.world(uuid)', [['coalesce(w.from_x, p.pos_x, 18), coalesce(w.from_y, p.pos_y, 22)', `coalesce(w.from_x, p.pos_x, ${sx}), coalesce(w.from_y, p.pos_y, ${sy})`]])}

-- ---------- the shops you buy and sell in ----------
${swap('public.buy_item(text)', [['p.pos_x between 30 and 34 and p.pos_y between 2 and 6', `p.pos_x between ${WEAPONS.x0} and ${WEAPONS.x1} and p.pos_y between ${WEAPONS.y0} and ${WEAPONS.y1}`]])}
${swap('public.sell_item(text)', [['p.pos_x between 16 and 20 and p.pos_y between 9 and 13', `p.pos_x between ${STORE.x0} and ${STORE.x1} and p.pos_y between ${STORE.y0} and ${STORE.y1}`]])}

-- ---------- the guard's route (src/game/watchers.ts GUARD_ROUTE) ----------
${swap('game.guard_at(bigint)', [
  ['rx int[] := array[36, 42, 42, 36, 36, 42, 42, 36];', `rx int[] := array[${GUARD_ROUTE.map((p) => p[0]).join(', ')}];`],
  ['ry int[] := array[21, 21, 25, 25, 28, 28, 25, 25];', `ry int[] := array[${GUARD_ROUTE.map((p) => p[1]).join(', ')}];`],
  ['n int := 8;', `n int := ${GUARD_ROUTE.length};`],
])}

-- ---------- the pigeon tiles (src/game/enemies.ts PIGEON_TILES: ${PIGEON_TILES.length} park tiles) ----------
${swapRe('game.pigeon_at(integer, bigint)', [
  ['px int\\[\\] := array\\[[0-9,]*\\];', `px int[] := array[${PIGEON_TILES.map((t) => t[0]).join(',')}];`],
  ['py int\\[\\] := array\\[[0-9,]*\\];', `py int[] := array[${PIGEON_TILES.map((t) => t[1]).join(',')}];`],
  ['n int := [0-9]+;', `n int := ${PIGEON_TILES.length};`],
])}

-- ---------- the crime spots (same ids, new places) ----------
update public.spots s set x = v.x, y = v.y, area_x0 = v.ax0, area_y0 = v.ay0, area_x1 = v.ax1, area_y1 = v.ay1
from (values
${spots.join(',\n')}
) as v(id, x, y, ax0, ay0, ax1, ay1)
where s.id = v.id;
do $$ begin
  if (select count(*) from public.spots) <> ${NODES.length} then raise exception 'spots: expected ${NODES.length} rows'; end if;
end $$;

-- ---------- DATA RESET: positions, attempts, fights, graves, routes ----------
update public.players set pos_x = null, pos_y = null, pos_at = now(),
  job_crime = null, job_spot = null, job_started_at = null, job_ends_at = null, job_pos_x = null, job_pos_y = null,
  caught_crime = null, caught_at = null, fight_enemy = null, fight_next = null;
update public.graves set x = ${sx + 1}, y = ${sy};
delete from public.walks;
update public.enemies set fighter = null, fight_x = null, fight_y = null, fight_seen = null, left_at = null, left_by = null, left_x = null, left_y = null;
`;
writeFileSync(new URL('../supabase/migrations/0013_new_city.sql', import.meta.url), sql);
console.log(`wrote 0013_new_city.sql (${sql.length} bytes, ${NODES.length} spots, ${PIGEON_TILES.length} pigeon tiles)`);
