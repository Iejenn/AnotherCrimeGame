// Writes docs/map.svg (the city with every block numbered and every lot lettered) and docs/map.md (what's on each
// lot), from src/street/map.ts, so the map we talk about is always the map in the game.
// Run: npx vite-node scripts/map-doc.ts
import { writeFileSync } from 'node:fs';
import { AREAS, BCOLS, BROWS, BLOCK_SIZE, COURT, H, LOTS, PARK, PARKING, ROOMS, SPAWN, W, blockName, blockRect, inRect, type Lot } from '../src/street/map';

const PX = 14; // pixels per tile
const M = 30; // margin
const COLORS: Record<string, string> = {
  street: '#3a3d44', sidewalk: '#6d6962', buildings: '#8a7f70', park: '#4f7a44', store: '#2f7a46', candy: '#b0588a', bar: '#7a5432',
  gas: '#3a5a8a', weapons: '#5a5a62', court: '#8a4434', parking: '#2a2c31', bigpark: '#4f7a44',
};

/** What's on a lot, in words, and its colour. */
function describe(lot: Lot): [string, string] {
  const c = (lot.rect.x0 + lot.rect.x1) / 2;
  const r = (lot.rect.y0 + lot.rect.y1) / 2;
  const room = ROOMS.find((x) => inRect(x, c, r));
  if (room) return [AREAS.find((a) => a.id === room.id)?.name ?? room.name, COLORS[room.id] ?? COLORS.buildings];
  if (inRect(COURT, c, r)) return ['Basketball court', COLORS.court];
  if (inRect(PARK, c, r)) return ['Central Park', COLORS.bigpark];
  if (PARKING.some((p) => inRect(p, c, r))) return ['Parking lot', COLORS.parking];
  if (lot.kind === 'park') return ['Pocket park', COLORS.park];
  return ['Buildings', COLORS.buildings];
}

const esc = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, '&#39;');
const X = (tx: number) => M + tx * PX;
const out: string[] = [];
const w = W * PX + 2 * M;
const h = H * PX + 2 * M + 30;
out.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" font-family="Arial, Helvetica, sans-serif">`);
out.push(`<rect width="${w}" height="${h}" fill="#15303f"/>`);
out.push(`<rect x="${X(0)}" y="${X(0)}" width="${W * PX}" height="${H * PX}" fill="${COLORS.street}"/>`);
// Sidewalks, then lots.
for (let bx = 0; bx < BCOLS; bx++)
  for (let by = 0; by < BROWS; by++) {
    const b = blockRect(bx, by);
    out.push(`<rect x="${X(b.x0 - 1.5)}" y="${X(b.y0 - 1.5)}" width="${(BLOCK_SIZE + 3) * PX}" height="${(BLOCK_SIZE + 3) * PX}" fill="${COLORS.sidewalk}"/>`);
  }
for (const lot of LOTS) {
  const [, color] = describe(lot);
  const r = lot.rect;
  out.push(`<rect x="${X(r.x0)}" y="${X(r.y0)}" width="${5 * PX}" height="${5 * PX}" fill="${color}" stroke="#1d1b19" stroke-width="1.5"/>`);
}
// Labels: lot letter in its corner, what's there in the middle; block number on its north edge.
for (const lot of LOTS) {
  const [what] = describe(lot);
  const r = lot.rect;
  out.push(`<text x="${X(r.x0) + 4}" y="${X(r.y0) + 13}" font-size="12" font-weight="700" fill="#ffffff" opacity="0.9">${lot.name.slice(4)}</text>`);
  const words = what.split(' ');
  const lines = words.length > 1 && what.length > 9 ? [words.slice(0, Math.ceil(words.length / 2)).join(' '), words.slice(Math.ceil(words.length / 2)).join(' ')] : [what];
  lines.forEach((l, i) =>
    out.push(`<text x="${X(r.x0 + 2.5)}" y="${X(r.y0 + 2.5) + (i - (lines.length - 1) / 2) * 12 + 4}" font-size="10" text-anchor="middle" fill="#ffffff">${esc(l)}</text>`),
  );
}
for (let bx = 0; bx < BCOLS; bx++)
  for (let by = 0; by < BROWS; by++) {
    const b = blockRect(bx, by);
    const cx = X(b.x0 + BLOCK_SIZE / 2);
    const cy = X(b.y0 - 1.5) + 1;
    out.push(`<rect x="${cx - 24}" y="${cy - 8}" width="48" height="17" rx="3" fill="#141210" stroke="#f2d27a"/>`);
    out.push(`<text x="${cx}" y="${cy + 5}" font-size="13" font-weight="700" text-anchor="middle" fill="#f2d27a">${blockName(bx, by)}</text>`);
  }
// Spawn and compass.
out.push(`<circle cx="${X(SPAWN[0] + 0.5)}" cy="${X(SPAWN[1] + 0.5)}" r="6" fill="#d9473a" stroke="#ffffff" stroke-width="2"/>`);
out.push(`<text x="${X(SPAWN[0] + 0.5) + 9}" y="${X(SPAWN[1] + 0.5) + 4}" font-size="11" font-weight="700" fill="#ffffff">Start</text>`);
out.push(`<text x="${w - 18}" y="20" font-size="14" font-weight="700" text-anchor="middle" fill="#ffffff">N ↑</text>`);
out.push(`<text x="${M}" y="${h - 12}" font-size="12" fill="#c8c4bc">Underworld: blocks 001–009 (row by row from the north-west), lots A B / C D. ${W}×${H} tiles. Generated by scripts/map-doc.ts.</text>`);
out.push('</svg>');
writeFileSync(new URL('../docs/map.svg', import.meta.url), out.join('\n'));

// The table.
const rows = LOTS.slice()
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((l) => `| ${l.name} | ${describe(l)[0]} | ${l.rect.x0}–${l.rect.x1} | ${l.rect.y0}–${l.rect.y1} |`);
const md = `# The city map

![The city, blocks numbered and lots lettered](map.svg)

To talk about a place, use its **block number** and **lot letter**: "002-C" is block 002, lot C (Eddy's).

- **Blocks** are numbered row by row from the north-west corner:

  \`\`\`
  001  002  003
  004  005  006
  007  008  009
  \`\`\`
- **Lots** in a block (each 5×5 tiles):

  \`\`\`
  A  B
  C  D
  \`\`\`
- Between the blocks are the streets (7 tiles: sidewalk, road, sidewalk). The red dot is where you start.
- In the code the same names are used: \`lot('002', 'C')\`, \`block('008')\` in \`src/street/map.ts\`.

This page and the picture are generated from the game's map: after changing \`src/street/map.ts\`, run
\`npx vite-node scripts/map-doc.ts\`.

| Lot | What's there | Tiles x | Tiles y |
|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(new URL('../docs/map.md', import.meta.url), md);
console.log(`wrote docs/map.svg (${w}×${h}) and docs/map.md (${rows.length} lots)`);
