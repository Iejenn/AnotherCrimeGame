// Writes supabase/migrations/0016_thugs.sql from the game's data (src/game/enemies.ts, items.ts, map.ts), so the
// server's thugs (stats, where they stroll, their schedule) and the knife can't disagree with the game.
// Run: npx vite-node scripts/thugs-sql.ts
import { writeFileSync } from 'node:fs';
import { ENEMIES, ENEMY_KINDS, THUG_MOVE_MS, THUG_TILES, THUG_WALK_MS } from '../src/game/enemies';
import { ITEM_BY_ID } from '../src/game/data/items';

const k = ENEMY_KINDS.thug;
const knife = ITEM_BY_ID.knife;
const g = knife.gear!;
const thugs = ENEMIES.filter((e) => e.kind === 'thug');

const sql = `-- 0016: the Yard's thugs and the knife (docs/design.md §12). GENERATED by scripts/thugs-sql.ts.
--
--  - enemy_kinds: the thug (level ${k.level}, ${k.hp} HP, attack ${k.attack}, defence ${k.defense}, max hit ${k.maxHit}, a stab every ${k.speed} ticks,
--    back ${k.respawn} s after a kill, not aggressive). enemies: ${thugs.map((t) => t.id).join(', ')}.
--  - loot: a thug drops $5–10 (1 in 5) and a knife (1 in 20), on the ground (0015).
--  - items: the knife (Melee ${g.needs?.level}, damage ${g.damage}, a stab every ${g.speed} ticks, worth $${knife.value}; Ray buys it for 25%).
--  - game.thug_at: where thug idx is at time t (the Yard's ${THUG_TILES.length} open tiles; a new spot every ${THUG_MOVE_MS / 1000} s, ${THUG_WALK_MS / 1000} s
--    to walk there), the same as thugAt() in src/game/enemies.ts. game.enemy_at picks pigeon_at or thug_at by kind,
--    and attack() uses it (it only knew pigeons).
-- Additive: new rows, two new functions, one changed line in attack (swapped in its live definition).

insert into public.items (id, name, slot, damage, accuracy, defence, speed, needs_skill, needs_level, heal, value)
values ('knife', '${knife.name}', 'weapon', ${g.damage}, ${g.accuracy ?? 0}, 0, ${g.speed}, '${g.needs?.skill}', ${g.needs?.level}, 0, ${knife.value})
on conflict (id) do update set name = excluded.name, slot = excluded.slot, damage = excluded.damage, accuracy = excluded.accuracy,
  speed = excluded.speed, needs_skill = excluded.needs_skill, needs_level = excluded.needs_level, value = excluded.value;

insert into public.enemy_kinds (id, name, level, hp, attack, defense, defence_bonus, speed, max_hit, respawn, aggressive)
values ('thug', '${k.name}', ${k.level}, ${k.hp}, ${k.attack}, ${k.defense}, ${k.defenceBonus}, ${k.speed}, ${k.maxHit}, ${k.respawn}, ${k.aggressive})
on conflict (id) do update set name = excluded.name, level = excluded.level, hp = excluded.hp, attack = excluded.attack, defense = excluded.defense,
  defence_bonus = excluded.defence_bonus, speed = excluded.speed, max_hit = excluded.max_hit, respawn = excluded.respawn, aggressive = excluded.aggressive;

insert into public.enemies (id, kind, idx, hp) values
${thugs.map((t) => `  ('${t.id}', 'thug', ${t.index}, ${k.hp})`).join(',\n')}
on conflict (id) do nothing;

insert into public.loot (enemy_kind, item, chance, min_amount, max_amount)
select 'thug', 'cash', 0.2, 5, 10 where not exists (select 1 from public.loot where enemy_kind = 'thug' and item = 'cash');
insert into public.loot (enemy_kind, item, chance, min_amount, max_amount)
select 'thug', 'knife', 0.05, 1, 1 where not exists (select 1 from public.loot where enemy_kind = 'thug' and item = 'knife');

-- Where thug idx is at time t (ms): the same schedule as thugAt() in the game.
create or replace function game.thug_at(idx int, t bigint, out x double precision, out z double precision, out flying boolean)
language plpgsql immutable set search_path = pg_catalog, game as $$
declare
  px int[] := array[${THUG_TILES.map((p) => p[0]).join(',')}];
  py int[] := array[${THUG_TILES.map((p) => p[1]).join(',')}];
  n int := ${THUG_TILES.length};
  shifted bigint := t + idx * 4111;
  k bigint := shifted / ${THUG_MOVE_MS};
  into_move bigint := shifted - k * ${THUG_MOVE_MS};
  a int;
  b int;
  f double precision;
begin
  flying := false;
  a := (game.minstd(((k * 3 + idx) % 2147483647) + 1) % n)::int + 1;
  if into_move >= ${THUG_WALK_MS} then
    x := px[a] + 0.5; z := py[a] + 0.5;
    return;
  end if;
  b := (game.minstd((((k - 1) * 3 + idx) % 2147483647) + 1) % n)::int + 1;
  f := into_move / ${THUG_WALK_MS}.0;
  x := px[b] + 0.5 + (px[a] - px[b]) * f;
  z := py[b] + 0.5 + (py[a] - py[b]) * f;
end $$;
revoke execute on function game.thug_at(int, bigint) from public, anon, authenticated;

-- Where an enemy of this kind is (each kind has its own schedule).
create or replace function game.enemy_at(p_kind text, idx int, t bigint, out x double precision, out z double precision, out flying boolean)
language plpgsql immutable set search_path = pg_catalog, game as $$
begin
  if p_kind = 'thug' then
    select * into x, z, flying from game.thug_at(idx, t);
  else
    select * into x, z, flying from game.pigeon_at(idx, t);
  end if;
end $$;
revoke execute on function game.enemy_at(text, int, bigint) from public, anon, authenticated;

do $do$
declare def text;
begin
  def := pg_get_functiondef('public.attack(text, integer, integer)'::regprocedure);
  if position('game.pigeon_at(e.idx, game.ms(now()))' in def) = 0 then raise exception 'attack: anchor not found'; end if;
  def := replace(def, 'game.pigeon_at(e.idx, game.ms(now()))', 'game.enemy_at(e.kind, e.idx, game.ms(now()))');
  execute def;
end $do$;
`;
writeFileSync(new URL('../supabase/migrations/0016_thugs.sql', import.meta.url), sql);
console.log(`wrote 0016_thugs.sql (${sql.length} bytes, ${THUG_TILES.length} yard tiles)`);
