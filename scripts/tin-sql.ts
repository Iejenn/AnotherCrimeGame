// Writes the server side of the tin tier, the Industrial zone and Tinkering (docs/design.md §14), from the game's data
// (metals.ts, items.ts, map.ts), in three files so each pastes in one go on a phone:
//   0023_industrial_zone_and_tin.sql  the bigger map, the tin items, the Factory's stations, armour in fights, selling
//   0024_tin_conversion.sql           brass knuckles / baseball bat / knife become the tin ones (in one transaction)
//   0025_tinkering.sql                the Tinkering skill: crafts, start_make / make_step / stop_make
// Run: npx vite-node scripts/tin-sql.ts
import { writeFileSync } from 'node:fs';
import { CRAFTS, METAL_ITEMS } from '../src/game/data/metals';
import { SHOPS } from '../src/game/data/items';
import { H, SEWER, STATIONS, W } from '../src/street/map';

const q = (s: string) => s.replace(/'/g, "''");
const lit = (s: string) => `E'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const out = (name: string, sql: string) => {
  writeFileSync(new URL(`../supabase/migrations/${name}`, import.meta.url), sql);
  console.log(`wrote ${name} (${sql.length} bytes)`);
};
/** A DO block that swaps lines in live function definitions, stopping if one isn't found. */
const swapBlock = (swaps: [string, string, string][]) => `do $do$
declare
  r record;
  def text;
begin
  for r in select * from (values
${swaps.map(([fn, a, b]) => `    ('${fn}', ${lit(a)}, ${lit(b)})`).join(',\n')}
  ) as t(fn, old_text, new_text) loop
    def := pg_get_functiondef(r.fn::regprocedure);
    if position(r.old_text in def) = 0 then raise exception '%: anchor not found: %', r.fn, r.old_text; end if;
    execute replace(def, r.old_text, r.new_text);
  end loop;
end $do$;`;

// ---------- part 1 ----------
const stations = STATIONS.filter((s) => s.kind !== 'bbq');
out(
  '0023_industrial_zone_and_tin.sql',
  `-- 0023 (part 1 of 3): the Industrial zone, the tin items, armour in fights, selling (docs/design.md §14).
-- GENERATED by scripts/tin-sql.ts. Run 0023, then 0024, then 0025.
--
--  - game.on_map: the map is ${W} tiles wide now (the Industrial zone east of the city).
--  - items: the tin tier from the formulas in metals.ts (salvage, sheet, knuckles, bat, knife, helmet, leg guards, vest).
--  - stations: the Factory's 3 plate presses and 3 workbenches.
--  - fights: your armour's defence bonus counts when an enemy swings at you (game.armour_bonus; it was always 0).
--  - selling: a quarter of the value, rounded down, but at least $1.
-- Additive: new rows and functions, and changed lines swapped in the live definitions (it stops if one isn't found).
-- No player data is changed here.

create or replace function game.on_map(x int, y int) returns boolean
language sql immutable set search_path = pg_catalog as $$
  select (x between 0 and ${W - 1} and y between 0 and ${H - 1}) or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})
$$;
revoke execute on function game.on_map(int, int) from public, anon, authenticated;

insert into public.items (id, name, slot, damage, accuracy, defence, speed, needs_skill, needs_level, heal, value) values
${METAL_ITEMS.map((i) => {
  const g = i.gear;
  return `  ('${i.id}', '${q(i.name)}', ${g ? `'${g.slot}'` : 'null'}, ${g?.damage ?? 0}, ${g?.accuracy ?? 0}, ${g?.defence ?? 0}, ${g?.speed ?? 'null'}, ${g?.needs ? `'${g.needs.skill}'` : 'null'}, ${g?.needs?.level ?? 1}, ${i.heal}, ${i.value})`;
}).join(',\n')}
on conflict (id) do update set name = excluded.name, slot = excluded.slot, damage = excluded.damage, accuracy = excluded.accuracy,
  defence = excluded.defence, speed = excluded.speed, needs_skill = excluded.needs_skill, needs_level = excluded.needs_level,
  heal = excluded.heal, value = excluded.value;

insert into public.stations (id, kind, x, y) values
${stations.map((s) => `  ('${s.id}', '${s.kind}', ${s.x}, ${s.y})`).join(',\n')}
on conflict (id) do update set kind = excluded.kind, x = excluded.x, y = excluded.y;

-- Your armour: the defence bonuses of what you wear on your head, body and legs, added up.
create or replace function game.armour_bonus(eq jsonb) returns int
language sql stable set search_path = pg_catalog, public as $$
  select coalesce(sum(i.defence), 0)::int from public.items i where i.id in (eq ->> 'head', eq ->> 'body', eq ->> 'legs')
$$;
revoke execute on function game.armour_bonus(jsonb) from public, anon, authenticated;

${swapBlock([
  ['public.fight_step()', '(game.level_from_xp(p.defense_xp) + 8) * (0 + 64)', '(game.level_from_xp(p.defense_xp) + 8) * (game.armour_bonus(p.equipment) + 64)'],
  ['public.sell_item(text)', 'floor(i.value * 0.25)::int', '(case when i.value > 0 then greatest(1, floor(i.value * 0.25)) else 0 end)::int'],
])}

-- Check: this should say "ok".
select case when game.on_map(${W - 1}, 10) and (select count(*) from public.stations where kind in ('press', 'bench')) = ${stations.length}
  and position('armour_bonus' in pg_get_functiondef('public.fight_step()'::regprocedure)) > 0
  and exists (select 1 from public.items where id = 'tin_vest') then 'ok' else 'NOT APPLIED' end as industrial_zone_and_tin;
`,
);

// ---------- part 2 ----------
const RENAMES: [string, string][] = [
  ['brass_knuckles', 'tin_knuckles'],
  ['baseball_bat', 'tin_bat'],
  ['knife', 'tin_knife'],
];
const inList = RENAMES.map(([a]) => `'${a}'`).join(', ');
const caseOld = (expr: string) => `case ${expr} ${RENAMES.map(([a, b]) => `when '${a}' then '${b}'`).join(' ')} end`;
const bagUpdate = (table: string, col: string) =>
  RENAMES.map(
    ([a, b]) =>
      `update public.${table} set ${col} = (${col} - '${a}') || jsonb_build_object('${b}', coalesce((${col} ->> '${b}')::int, 0) + (${col} ->> '${a}')::int) where ${col} ? '${a}';`,
  ).join('\n');
out(
  '0024_tin_conversion.sql',
  `-- 0024 (part 2 of 3): the old weapons become the tin ones (docs/design.md §14). GENERATED by scripts/tin-sql.ts.
-- Run after 0023.
--
-- ⚠ CHANGES PLAYER DATA (on purpose, nobody loses anything): Brass Knuckles → Tin Knuckles, Baseball Bat → Tin Bat,
-- Knife → Tin Knife, in every bag, in what people wield, in graves and on the ground. The thugs drop the tin knife; Ray
-- sells the three tin weapons (knuckles $${SHOPS.weapons[0].price}, bat $${SHOPS.weapons[1].price}, knife $${SHOPS.weapons[2].price}); the old items are removed.
-- It all runs in one transaction: if anything goes wrong, nothing is changed.
-- DRY RUN: change the last line "commit;" to "rollback;", run it, look at the result, then run it again with "commit;".

begin;

-- In bags and graves: the old item's count moves to the tin one.
${bagUpdate('players', 'inventory')}
${bagUpdate('graves', 'items')}
-- What people wield.
update public.players set equipment = jsonb_set(equipment, '{weapon}', to_jsonb(${caseOld("equipment ->> 'weapon'")}))
where equipment ->> 'weapon' in (${inList});
-- On the ground, in the thugs' loot, in Ray's shop.
update public.ground_items set item = ${caseOld('item')} where item in (${inList});
update public.loot set item = ${caseOld('item')} where item in (${inList});
delete from public.shop_items where shop = 'weapons';
insert into public.shop_items (shop, item, price) values
${SHOPS.weapons.map((w) => `  ('weapons', '${w.item}', ${w.price})`).join(',\n')};
-- The old items.
delete from public.items where id in (${inList});

-- Check: nothing old is left anywhere (stops and undoes everything if something is).
do $do$
begin
  if exists (select 1 from public.players where inventory ?| array[${inList}] or equipment ->> 'weapon' in (${inList}))
     or exists (select 1 from public.graves where items ?| array[${inList}])
     or exists (select 1 from public.ground_items where item in (${inList}))
     or exists (select 1 from public.loot where item in (${inList})) then
    raise exception 'old weapons are still somewhere: nothing was changed';
  end if;
end $do$;
select (select count(*) from public.players where equipment ->> 'weapon' like 'tin_%') as wielding_tin,
  (select string_agg(item || ' $' || price, ', ') from public.shop_items where shop = 'weapons') as rays_shop;

commit;
`,
);

