out(
  '0025_tinkering.sql',
  `-- 0025 (part 3 of 3): Tinkering, the 8th skill (docs/design.md §14). GENERATED by scripts/tin-sql.ts. Run after 0024.
--
--  - players.tinkering_xp, make_craft / make_next (what you're making and when the next one is done);
--  - crafts: what you make where (press: salvage → sheet; workbench: sheets → gear), the level, XP and ticks — the same
--    rows as CRAFTS in src/game/data/metals.ts;
--  - start_make(craft, x, y): at a press or workbench (next to it), with the level and the materials;
--    make_step(): makes every one that's done by now, until the materials run out (like cook_step); stop_make();
--  - save, respond and get_highscores know Tinkering and what you're making.
-- Additive: new columns, table and functions, and changed lines swapped in the live definitions. No data is changed.

alter table public.players add column if not exists tinkering_xp bigint not null default 0;
alter table public.players add column if not exists make_craft text;
alter table public.players add column if not exists make_next timestamptz;

create table if not exists public.crafts (
  id text primary key references public.items (id),  -- the item it makes
  station_kind text not null,                        -- 'press' or 'bench'
  skill text not null,
  level int not null,
  xp int not null,
  ticks int not null,                                -- × 0.5 s for one
  inputs jsonb not null                              -- { item: how many }
);
alter table public.crafts enable row level security;
insert into public.crafts (id, station_kind, skill, level, xp, ticks, inputs) values
${CRAFTS.map((c) => `  ('${c.id}', '${c.station}', '${c.skill}', ${c.level}, ${c.xp}, ${c.ticks}, '${JSON.stringify(c.inputs)}'::jsonb)`).join(',\n')}
on conflict (id) do update set station_kind = excluded.station_kind, skill = excluded.skill, level = excluded.level, xp = excluded.xp,
  ticks = excluded.ticks, inputs = excluded.inputs;

-- Start making something: as many as your materials allow, one after another.
create or replace function public.start_make(p_craft text, p_x int, p_y int)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  rep jsonb := game.empty_report();
  logs jsonb := '[]'::jsonb;
  r record;
  c public.crafts;
  i record;
begin
  if p.id is null then return jsonb_build_object('ok', false, 'reason', 'no_character'); end if;
  select * into r from game.settle(p, rep, logs);
  p := r.p; rep := r.rep; logs := r.logs;
  if p.job_crime is not null or p.caught_crime is not null or p.fight_enemy is not null then
    perform game.save(p); return game.respond(p.id, false, 'busy', rep, logs);
  end if;
  if p.stunned_until > now() then perform game.save(p); return game.respond(p.id, false, 'stunned', rep, logs); end if;
  if not game.can_reach(p, p_x, p_y) then perform game.save(p); return game.respond(p.id, false, 'too_fast', rep, logs); end if;
  select * into c from public.crafts where id = p_craft;
  if c.id is null then perform game.save(p); return game.respond(p.id, false, 'unknown_craft', rep, logs); end if;
  if not exists (select 1 from public.stations s where s.kind = c.station_kind and greatest(abs(p_x - s.x), abs(p_y - s.y)) <= 1) then
    perform game.save(p); return game.respond(p.id, false, 'not_at_station', rep, logs);
  end if;
  if game.level_from_xp(p.tinkering_xp) < c.level then perform game.save(p); return game.respond(p.id, false, 'level_too_low', rep, logs); end if;
  for i in select key, value::int as n from jsonb_each_text(c.inputs) loop
    if coalesce((p.inventory ->> i.key)::int, 0) < i.n then perform game.save(p); return game.respond(p.id, false, 'no_materials', rep, logs); end if;
  end loop;
  p.cook_item := null; p.cook_next := null;
  p.make_craft := c.id;
  p.make_next := now() + make_interval(secs => c.ticks * 0.5);
  p.pos_x := p_x; p.pos_y := p_y; p.pos_at := now();
  logs := logs || to_jsonb('You get to work.'::text);
  perform game.save(p);
  return game.respond(p.id, true, null, rep, logs);
end $$;
grant execute on function public.start_make(text, int, int) to authenticated;
revoke execute on function public.start_make(text, int, int) from public, anon;

-- Make every one that's done by now (one every few ticks), until the materials run out.
create or replace function public.make_step()
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  rep jsonb := game.empty_report();
  logs jsonb := '[]'::jsonb;
  r record;
  c public.crafts;
  i record;
  enough boolean;
  lv0 int;
  n int := 0;
  v_name text;
begin
  if p.id is null then return jsonb_build_object('ok', false, 'reason', 'no_character'); end if;
  select * into r from game.settle(p, rep, logs);
  p := r.p; rep := r.rep; logs := r.logs;
  if p.make_craft is null then perform game.save(p); return game.respond(p.id, false, 'no_making', rep, logs); end if;
  -- Doing something else stops it.
  if p.job_crime is not null or p.fight_enemy is not null or p.caught_crime is not null or p.cook_item is not null then
    p.make_craft := null; p.make_next := null;
    perform game.save(p); return game.respond(p.id, false, 'no_making', rep, logs);
  end if;
  if p.make_next > now() then perform game.save(p); return game.respond(p.id, false, 'not_yet', rep, logs); end if;
  select * into c from public.crafts where id = p.make_craft;
  select name into v_name from public.items where id = c.id;
  lv0 := game.level_from_xp(p.tinkering_xp);
  while p.make_craft is not null and p.make_next <= now() and n < 60 loop
    n := n + 1;
    enough := c.id is not null;
    for i in select key, value::int as k from jsonb_each_text(coalesce(c.inputs, '{}'::jsonb)) loop
      if coalesce((p.inventory ->> i.key)::int, 0) < i.k then enough := false; end if;
    end loop;
    if not enough then
      p.make_craft := null; p.make_next := null;
      exit;
    end if;
    for i in select key, value::int as k from jsonb_each_text(c.inputs) loop
      p.inventory := case when (p.inventory ->> i.key)::int = i.k then p.inventory - i.key
                          else jsonb_set(p.inventory, array[i.key], to_jsonb((p.inventory ->> i.key)::int - i.k)) end;
    end loop;
    p.inventory := jsonb_set(p.inventory, array[c.id], to_jsonb(coalesce((p.inventory ->> c.id)::int, 0) + 1));
    p.tinkering_xp := p.tinkering_xp + c.xp;
    rep := jsonb_set(rep, '{xp,tinkering}', to_jsonb(coalesce((rep -> 'xp' ->> 'tinkering')::numeric, 0) + c.xp));
    rep := jsonb_set(rep, array['items', c.id], to_jsonb(coalesce((rep -> 'items' ->> c.id)::int, 0) + 1));
    logs := logs || to_jsonb(format('You %s a %s. +%s XP', case c.station_kind when 'press' then 'press' else 'make' end, lower(v_name), c.xp));
    p.make_next := p.make_next + make_interval(secs => c.ticks * 0.5);
  end loop;
  -- Enough left for the next one?
  if p.make_craft is not null then
    for i in select key, value::int as k from jsonb_each_text(c.inputs) loop
      if coalesce((p.inventory ->> i.key)::int, 0) < i.k then p.make_craft := null; p.make_next := null; end if;
    end loop;
  end if;
  if p.make_craft is null then logs := logs || to_jsonb('You have no materials left.'::text); end if;
  if game.level_from_xp(p.tinkering_xp) > lv0 then
    rep := jsonb_set(rep, '{levelUps}', (rep -> 'levelUps') || jsonb_build_object('skill', 'tinkering', 'level', game.level_from_xp(p.tinkering_xp)));
    logs := logs || to_jsonb(format('Tinkering reached level %s!', game.level_from_xp(p.tinkering_xp)));
  end if;
  perform game.save(p);
  return game.respond(p.id, true, null, rep, logs);
end $$;
grant execute on function public.make_step() to authenticated;
revoke execute on function public.make_step() from public, anon;

create or replace function public.stop_make()
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
begin
  if p.id is null then return jsonb_build_object('ok', false, 'reason', 'no_character'); end if;
  update public.players set make_craft = null, make_next = null, updated_at = now() where id = p.id;
  return game.respond(p.id, true, null, null, null);
end $$;
grant execute on function public.stop_make() to authenticated;
revoke execute on function public.stop_make() from public, anon;

${swapBlock([
  ['game.save(public.players)', 'scrapping_xp = p.scrapping_xp,', 'scrapping_xp = p.scrapping_xp, tinkering_xp = p.tinkering_xp, make_craft = p.make_craft, make_next = p.make_next,'],
  ['game.respond(uuid, boolean, text, jsonb, jsonb)', "'scrapping', jsonb_build_object('xp', p.scrapping_xp))",
    "'scrapping', jsonb_build_object('xp', p.scrapping_xp), 'tinkering', jsonb_build_object('xp', p.tinkering_xp))"],
  ['game.respond(uuid, boolean, text, jsonb, jsonb)', "'cook', case when p.cook_item is null then null else jsonb_build_object('item', p.cook_item, 'next', game.ms(p.cook_next)) end",
    "'cook', case when p.cook_item is null then null else jsonb_build_object('item', p.cook_item, 'next', game.ms(p.cook_next)) end,\n      'make', case when p.make_craft is null then null else jsonb_build_object('craft', p.make_craft, 'next', game.ms(p.make_next)) end"],
  ['public.get_highscores(text, integer)', "when 'scrapping' then 'scrapping_xp' end;", "when 'scrapping' then 'scrapping_xp' when 'tinkering' then 'tinkering_xp' end;"],
])}

-- Check: this should say "ok".
select case when (select count(*) from public.crafts) = ${CRAFTS.length}
  and position('tinkering_xp' in pg_get_functiondef('game.save(public.players)'::regprocedure)) > 0
  and position('make_craft' in pg_get_functiondef('game.respond(uuid, boolean, text, jsonb, jsonb)'::regprocedure)) > 0
  then 'ok' else 'NOT APPLIED' end as tinkering;
`,
);
