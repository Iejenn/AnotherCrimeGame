// Writes supabase/migrations/0022_scrapping.sql from the game's data (crimes.ts, items.ts, map.ts), so the server's
// Scrapping (the tin salvage "crime", the Thrift Store's dumpsters, the item) can't disagree with the game.
// Run: npx vite-node scripts/scrapping-sql.ts
import { writeFileSync } from 'node:fs';
import { CRIME_BY_ID } from '../src/game/data/crimes';
import { ITEM_BY_ID } from '../src/game/data/items';
import { NODES } from '../src/street/map';

const c = CRIME_BY_ID.tin_salvage;
const item = ITEM_BY_ID.tin_salvage;
const spots = NODES.filter((n) => n.crimeId === c.id);
const q = (s: string) => s.replace(/'/g, "''");

/** The changed lines in existing functions: [function, the text as it is now, what it becomes]. */
const swaps: [string, string, string][] = [
  // start_attempt: the level you need is in the crime's own skill.
  ['public.start_attempt(text, integer, integer)', 'if game.level_from_xp(p.street_xp) < c.level then',
    "if game.level_from_xp(case c.skill when 'scrapping' then p.scrapping_xp else p.street_xp end) < c.level then"],
  // finish_attempt: the skill's XP and level, no big scores for scrapping, the item's real name, the right words.
  ['public.finish_attempt()', 'lvl_before := game.level_from_xp(p.street_xp);',
    "lvl_before := game.level_from_xp(case c.skill when 'scrapping' then p.scrapping_xp else p.street_xp end);"],
  ['public.finish_attempt()', 'big := random() < 0.05;', "big := c.skill = 'street' and random() < 0.05;"],
  ['public.finish_attempt()', "'%sYou got away with it. +%s %s, +%s XP'",
    "'%s' || case c.skill when 'scrapping' then 'You find something useful.' else 'You got away with it.' end || ' +%s %s, +%s XP'"],
  ['public.finish_attempt()', "case v_item when 'sandwich' then 'Sandwich' else 'Candy Bar' end",
    'coalesce((select i.name from public.items i where i.id = v_item), v_item)'],
  ['public.finish_attempt()', 'p.street_xp := p.street_xp + v_xp;',
    "if c.skill = 'scrapping' then p.scrapping_xp := p.scrapping_xp + v_xp; else p.street_xp := p.street_xp + v_xp; end if;"],
  ['public.finish_attempt()', "jsonb_build_object('street', v_xp)", 'jsonb_build_object(c.skill, v_xp)'],
  ['public.finish_attempt()', 'lvl_after := game.level_from_xp(p.street_xp);',
    "lvl_after := game.level_from_xp(case c.skill when 'scrapping' then p.scrapping_xp else p.street_xp end);"],
  ['public.finish_attempt()', "jsonb_build_object('skill', 'street', 'level', v_n)", "jsonb_build_object('skill', c.skill, 'level', v_n)"],
  ['public.finish_attempt()', "format('Street Crimes reached level %s!', v_n)",
    "format('%s reached level %s!', case c.skill when 'scrapping' then 'Scrapping' else 'Street Crimes' end, v_n)"],
  // Finding nothing in a dumpster: no catcher, no damage, no stun.
  ['public.finish_attempt()', '    if c.catcher is not null then\n      p.caught_crime := c.id;',
    "    if c.fail_damage = 0 and c.catcher is null then\n      logs := logs || to_jsonb('You find nothing useful.'::text);\n    elsif c.catcher is not null then\n      p.caught_crime := c.id;"],
  // save, respond, highscores: Scrapping.
  ['game.save(public.players)', 'cooking_xp = p.cooking_xp,', 'cooking_xp = p.cooking_xp, scrapping_xp = p.scrapping_xp,'],
  ['game.respond(uuid, boolean, text, jsonb, jsonb)', "'cooking', jsonb_build_object('xp', p.cooking_xp))",
    "'cooking', jsonb_build_object('xp', p.cooking_xp), 'scrapping', jsonb_build_object('xp', p.scrapping_xp))"],
  ['public.get_highscores(text, integer)', "when 'cooking' then 'cooking_xp' end;", "when 'cooking' then 'cooking_xp' when 'scrapping' then 'scrapping_xp' end;"],
];
/** A SQL string literal (E'' so the newlines in a few anchors survive). */
const lit = (s: string) => `E'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

const sql = `-- 0022: Scrapping, the 7th skill, and the Thrift Store's dumpsters (docs/design.md §14). GENERATED by
-- scripts/scrapping-sql.ts.
--
-- Scrapping uses the street-crime machinery (spots, attempts, empty spots that refill), with a skill per crime:
--  - players.scrapping_xp; crimes.skill ('street' for every crime there is, 'scrapping' for the new one);
--  - the crime ${c.id}: ${c.ticks} ticks a try, ${c.baseChance * 100}% to find something (+0.5% a level), ${c.xp} XP, 1 ${item.name}; finding
--    nothing costs nothing (no damage, no stun: "You find nothing useful."); a dumpster you found something in is empty
--    for ${c.refill} s;
--  - spots: the ${spots.length} dumpsters behind the Thrift Store (009); the item ${item.id} ($${item.value});
--  - start_attempt checks the crime's own skill level; finish_attempt gives the XP (and level-ups) to that skill, names
--    the item it gave you, and has no big scores for scrapping; save, respond and get_highscores know Scrapping.
-- Changed lines are swapped in the live definitions (it stops if one isn't found). Additive: no player data is changed.

alter table public.players add column if not exists scrapping_xp bigint not null default 0;
alter table public.crimes add column if not exists skill text not null default 'street';

insert into public.items (id, name, slot, damage, accuracy, defence, speed, needs_skill, needs_level, heal, value)
values ('${item.id}', '${q(item.name)}', null, 0, 0, 0, null, null, 1, 0, ${item.value})
on conflict (id) do update set name = excluded.name, value = excluded.value;

insert into public.crimes (id, name, level, ticks, base_chance, xp, cash_min, cash_max, items, fail_damage, fail_stun, catcher, refill, skill)
values ('${c.id}', '${q(c.name)}', ${c.level}, ${c.ticks}, ${c.baseChance}, ${c.xp}, ${c.cashMin}, ${c.cashMax}, array[${(c.items ?? []).map((i) => `'${i}'`).join(', ')}]::text[],
  ${c.failDamage}, ${c.failStun}, null, ${c.refill}, '${c.skill}')
on conflict (id) do update set name = excluded.name, level = excluded.level, ticks = excluded.ticks, base_chance = excluded.base_chance,
  xp = excluded.xp, items = excluded.items, fail_damage = excluded.fail_damage, fail_stun = excluded.fail_stun, refill = excluded.refill,
  skill = excluded.skill;

insert into public.spots (id, crime_id, x, y) values
${spots.map((n) => `  ('${n.id}', '${c.id}', ${n.x}, ${n.y})`).join(',\n')}
on conflict (id) do update set crime_id = excluded.crime_id, x = excluded.x, y = excluded.y;

do $do$
declare
  r record;
  def text;
begin
  for r in select * from (values
${swaps.map(([fn, a, b]) => `    ('${fn}', ${lit(a)}, ${lit(b)})`).join(',\n')}
  ) as t(fn, old_text, new_text) loop
    def := pg_get_functiondef(r.fn::regprocedure);
    if position(r.old_text in def) = 0 then raise exception '%: anchor not found: %', r.fn, r.old_text; end if;
    execute replace(def, r.old_text, r.new_text);
  end loop;
end $do$;

-- Check: this should say "ok".
select case when (select count(*) from public.spots where crime_id = '${c.id}') = ${spots.length}
  and position('scrapping_xp' in pg_get_functiondef('public.finish_attempt()'::regprocedure)) > 0
  and position('scrapping_xp' in pg_get_functiondef('game.respond(uuid, boolean, text, jsonb, jsonb)'::regprocedure)) > 0
  then 'ok' else 'NOT APPLIED' end as scrapping;
`;
writeFileSync(new URL('../supabase/migrations/0022_scrapping.sql', import.meta.url), sql);
console.log(`wrote 0022_scrapping.sql (${sql.length} bytes, ${spots.length} dumpsters)`);
