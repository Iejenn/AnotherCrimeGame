// Prints supabase/migrations/0037_bigger_map.sql (v0.54): everything the server keeps of the map, from the map itself.
// The map grew a row of districts to the south; the park became a big cross with the Plaza; Eddy's, Ray's, the bar,
// the gas station and the parking lot moved; the sewer (drawn below the island in the game's grid) moved down with it.
// Run: npx vite-node scripts/map-v054-sql.ts > supabase/migrations/0037_bigger_map.sql
// (src/street/mapSql.test.ts checks the migration is exactly what this prints.)
declare const process: { env: Record<string, string | undefined>; stdout: { write(s: string): void } };
import {
  BAR, ENCLOSURES, H, LINKS, NEST, NEST_GATE, NEST_LOCKED, NEST_TUNNEL, NODES, SEWER, SPAWN, SPLINTER, STATIONS, STORE, VACATED_RECTS, W,
  WEAPONS, GH,
} from '../src/street/map';
import { ENEMIES, ENEMY_KINDS, PIGEON_TILES, RAT_ZONES, ROAMS } from '../src/game/enemies';
import { allDetours } from '../src/game/roamPaths';
import { GUARD_ROUTE } from '../src/game/watchers';
import { SHOT_WALLS, walkMasks } from '../src/street/sight';

// The old map's numbers, as the live functions have them (the anchors the patches look for).
const OLD_H = 58;
const SHIFT = H - OLD_H; // how far the sewer moved down
const OLD = { spawn: [79, 43], store: [75, 79], weapons: [80, 84], shopY: [12, 16], gate: [44, 65], splinter: [40, 64] };
if (SHIFT !== 51) throw new Error(`unexpected shift ${SHIFT}`);

const arr = (xs: number[]) => `array[${xs.join(',')}]`;
export function bigMapSql(): string {
const out: string[] = [];
const say = (s: string) => out.push(s);

/** A DO block that edits a function's live definition: each [old, new] must be found exactly once. */
const patch = (sig: string, pairs: [string, string][]) => {
  say(`do $do$
declare def text := pg_get_functiondef('${sig}'::regprocedure);
begin
${pairs
  .map(
    ([a, b]) => `  if (length(def) - length(replace(def, $a$${a}$a$, ''))) / length($a$${a}$a$) <> 1 then raise exception '${sig}: anchor not found once: %', $a$${a}$a$; end if;
  def := replace(def, $a$${a}$a$, $b$${b}$b$);`,
  )
  .join('\n')}
  execute def;
end $do$;`);
};

say(`-- 0037_bigger_map (v0.54): the map grew. GENERATED by scripts/map-v054-sql.ts from the game's map: don't edit by hand.
--
-- What changes on the server (everything it keeps of the map):
--  - The island is ${W} × ${H} tiles now (was ${W} × ${OLD_H}): a new row of districts to the south.
--  - The sewer is drawn below the island in the game's grid, so it moved down ${SHIFT} tiles: the rats, the Rat Nest and its
--    gate, Splinter, the ladder, the fire barrel. Anyone and anything down there right now moves with it (players,
--    their walk, items on the ground, graves, fights): nobody notices.
--  - Central Park is a big cross with the Plaza in the middle: 8 Pigeons (were 3) and 6 tourists (were 3) live there.
--    New players start on the Plaza (${SPAWN[0]}, ${SPAWN[1]}).
--  - Moved: Eddy's and Ray's (to F-002), the bar (I-009-C), the gas station and the parking lot with its guard (F-015).
--    Players standing where those were (ordinary buildings now) are moved to the Plaza.
--  - Regenerated from the map: the crime spots, line of sight (walls, enclosures), the enemies' walk map and their
--    walks round things, the climbing links, the cooking stations.
--
-- Nothing is deleted except rows that are rebuilt from the map right here (walls, walk map, walks round things).
-- Functions are edited from their live definitions (each edit checks its anchor) or replaced with the same signature.
-- One transaction: to try it first, replace "commit;" at the end with "rollback;". The check should say "ok".

begin;

-- ---------- 1. Move what's underground down ${SHIFT} tiles (only once: while the island still ends at y ${OLD_H - 1}) ----------
do $do$
begin
  if position('between 0 and ${OLD_H - 1}' in pg_get_functiondef('game.on_map(integer, integer)'::regprocedure)) = 0 then
    raise notice 'already moved';
    return;
  end if;
  update public.players set pos_y = pos_y + ${SHIFT} where pos_y >= ${OLD_H};
  update public.players set job_pos_y = job_pos_y + ${SHIFT} where job_pos_y >= ${OLD_H};
  update public.walks set from_y = from_y + ${SHIFT},
    path = coalesce((select jsonb_agg(jsonb_build_array((e ->> 0)::int, (e ->> 1)::int + ${SHIFT}) order by i) from jsonb_array_elements(path) with ordinality as a(e, i)), '[]'::jsonb)
  where from_y >= ${OLD_H};
  update public.ground_items set y = y + ${SHIFT} where y >= ${OLD_H};
  update public.graves set y = y + ${SHIFT} where y >= ${OLD_H};
  update public.enemies set
    fight_y = case when fight_y >= ${OLD_H} then fight_y + ${SHIFT} else fight_y end,
    left_y = case when left_y >= ${OLD_H} then left_y + ${SHIFT} else left_y end,
    from_y = case when from_y >= ${OLD_H} then from_y + ${SHIFT} else from_y end,
    route = case when route is null or from_y < ${OLD_H} then route
      else coalesce((select jsonb_agg(jsonb_build_array((e ->> 0)::int, (e ->> 1)::int + ${SHIFT}) order by i) from jsonb_array_elements(route) with ordinality as a(e, i)), '[]'::jsonb) end
  where kind in ('rat', 'giant_rat');
  -- Players standing where Eddy's, Ray's, the bar, the gas station or the parking lot were (buildings now): to the Plaza.
  update public.walks w set from_x = ${SPAWN[0]}, from_y = ${SPAWN[1]}, path = '[]'::jsonb, started_at = now()
  from public.players p where p.id = w.player_id and (${VACATED_RECTS.map((r) => `(p.pos_x between ${r.x0} and ${r.x1} and p.pos_y between ${r.y0} and ${r.y1})`).join(' or ')});
  update public.players set pos_x = ${SPAWN[0]}, pos_y = ${SPAWN[1]}, pos_at = now()
  where ${VACATED_RECTS.map((r) => `(pos_x between ${r.x0} and ${r.x1} and pos_y between ${r.y0} and ${r.y1})`).join(' or ')};
end $do$;

-- ---------- 2. Where you may be: the bigger island, the sewer, the tunnel and the nest ----------
create or replace function game.on_map(x integer, y integer)
 returns boolean
 language sql
 immutable
 set search_path to 'pg_catalog'
as $$
  select (x between 0 and ${W - 1} and y between 0 and ${H - 1})
    or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})
    or (x between ${NEST_TUNNEL.x0} and ${NEST_TUNNEL.x1} and y between ${NEST_TUNNEL.y0} and ${NEST_TUNNEL.y1})
    or (x between ${NEST.x0} and ${NEST.x1} and y between ${NEST.y0} and ${NEST.y1})
$$;
revoke execute on function game.on_map(integer, integer) from public, anon, authenticated;

create or replace function game.nest_locked(x integer, y integer)
 returns boolean
 language sql
 immutable
 set search_path to 'pg_catalog'
as $$
  select (x between ${NEST_LOCKED.x0} and ${NEST_TUNNEL.x1} and y = ${NEST_TUNNEL.y0}) or (x between ${NEST.x0} and ${NEST.x1} and y between ${NEST.y0} and ${NEST.y1})
$$;
revoke execute on function game.nest_locked(integer, integer) from public, anon, authenticated;
`);

patch('public.unlock_gate(text, integer, integer)', [[`abs(p_x - ${OLD.gate[0]}), abs(p_y - ${OLD.gate[1]})`, `abs(p_x - ${NEST_GATE[0]}), abs(p_y - ${NEST_GATE[1]})`]]);
patch('public.quest_talk(text, text, integer, integer)', [[`abs(p_x - ${OLD.splinter[0]}), abs(p_y - ${OLD.splinter[1]})`, `abs(p_x - ${SPLINTER[0]}), abs(p_y - ${SPLINTER[1]})`]]);

// The shops.
const inRoom = (v: string, r: { x0: number; x1: number; y0: number; y1: number }, axis: 'x' | 'y') =>
  axis === 'x' ? `${v} between ${r.x0} and ${r.x1}` : `${v} between ${r.y0} and ${r.y1}`;
patch('public.buy_item(text)', [[
  `p.pos_x between ${OLD.weapons[0]} and ${OLD.weapons[1]} and p.pos_y between ${OLD.shopY[0]} and ${OLD.shopY[1]}`,
  `${inRoom('p.pos_x', WEAPONS, 'x')} and ${inRoom('p.pos_y', WEAPONS, 'y')}`,
]]);
if (STORE.y0 !== WEAPONS.y0 || STORE.y1 !== WEAPONS.y1) throw new Error('sell_item assumes the shops share their rows');
patch('public.sell_item(text)', [[
  `p.pos_y between ${OLD.shopY[0]} and ${OLD.shopY[1]} and case when is_weapon then p.pos_x between ${OLD.weapons[0]} and ${OLD.weapons[1]} else p.pos_x between ${OLD.store[0]} and ${OLD.store[1]} end`,
  `${inRoom('p.pos_y', STORE, 'y')} and case when is_weapon then ${inRoom('p.pos_x', WEAPONS, 'x')} else ${inRoom('p.pos_x', STORE, 'x')} end`,
]]);

// The spawn (where someone with no position yet is).
patch('game.can_reach(players, integer, integer)', [[`coalesce(p.pos_x, ${OLD.spawn[0]})`, `coalesce(p.pos_x, ${SPAWN[0]})`], [`coalesce(p.pos_y, ${OLD.spawn[1]})`, `coalesce(p.pos_y, ${SPAWN[1]})`]]);
patch('game.world(uuid)', [[`coalesce(w.from_x, p.pos_x, ${OLD.spawn[0]})`, `coalesce(w.from_x, p.pos_x, ${SPAWN[0]})`], [`coalesce(w.from_y, p.pos_y, ${OLD.spawn[1]})`, `coalesce(w.from_y, p.pos_y, ${SPAWN[1]})`]]);

// The guard's route (the parking lot moved to F-015).
patch('game.guard_at(bigint)', [
  ['rx int[] := array[97, 101, 101, 93, 97];', `rx int[] := array[${GUARD_ROUTE.map((p) => p[0]).join(', ')}];`],
  ['ry int[] := array[27, 27, 30, 30, 30];', `ry int[] := array[${GUARD_ROUTE.map((p) => p[1]).join(', ')}];`],
]);

// The pigeons: the whole park now, and eight of them.
say(`
-- ---------- 3. The Pigeons: ${PIGEON_TILES.length} tiles of the big park; 8 of them ----------
create or replace function game.pigeon_at(idx integer, t bigint, out x double precision, out z double precision, out flying boolean)
 returns record
 language plpgsql
 immutable
 set search_path to 'pg_catalog', 'game'
as $$
declare
  px int[] := ${arr(PIGEON_TILES.map((t) => t[0]))};
  py int[] := ${arr(PIGEON_TILES.map((t) => t[1]))};
  n int := ${PIGEON_TILES.length};
  shifted bigint := t + idx * 2777;
  k bigint := shifted / 8000;
  into_hop bigint := shifted - k * 8000;
  a int;
  b int;
  f double precision;
begin
  a := (game.minstd(((k * 3 + idx) % 2147483647) + 1) % n)::int + 1;
  if into_hop >= 1500 then
    x := px[a] + 0.5; z := py[a] + 0.5; flying := false;
    return;
  end if;
  b := (game.minstd((((k - 1) * 3 + idx) % 2147483647) + 1) % n)::int + 1;
  f := into_hop / 1500.0;
  x := px[b] + 0.5 + (px[a] - px[b]) * f;
  z := py[b] + 0.5 + (py[a] - py[b]) * f;
  flying := true;
end $$;
revoke execute on function game.pigeon_at(integer, bigint) from public, anon, authenticated;
insert into public.enemies (id, kind, idx, hp) values
${ENEMIES.filter((e) => e.kind === 'pigeon').map((e) => `  ('${e.id}', 'pigeon', ${e.index}, ${ENEMY_KINDS.pigeon.hp})`).join(',\n')}
on conflict (id) do nothing;`);

// The rats and the giant rats moved down with the sewer.
const ratTiles = RAT_ZONES.flat();
const zs: number[] = [];
let at = 1;
for (const z of RAT_ZONES) zs.push(at), (at += z.length);
say(`
-- ---------- 4. The rats and the giant rats (down with the sewer) ----------
create or replace function game.rat_at(idx integer, t bigint, out x double precision, out z double precision, out flying boolean)
 returns record
 language plpgsql
 stable
 set search_path to 'pg_catalog', 'game'
as $$
declare
  px int[] := ${arr(ratTiles.map((t) => t[0]))};
  py int[] := ${arr(ratTiles.map((t) => t[1]))};
  zs int[] := ${arr(zs)};
  zn int[] := ${arr(RAT_ZONES.map((z) => z.length))};
  shifted bigint := t + idx * 3331;
  k bigint := shifted / 9000;
  into_move bigint := shifted - k * 9000;
  a int;
  b int;
begin
  flying := false;
  a := zs[idx + 1] + (game.minstd(((k * 3 + idx) % 2147483647) + 1) % zn[idx + 1])::int;
  if into_move >= 2000 then
    x := px[a] + 0.5; z := py[a] + 0.5;
    return;
  end if;
  b := zs[idx + 1] + (game.minstd((((k - 1) * 3 + idx) % 2147483647) + 1) % zn[idx + 1])::int;
  select w.x, w.z into x, z from game.walk_point(px[b], py[b], px[a], py[a], into_move / 2000.0) w;
end $$;
revoke execute on function game.rat_at(integer, bigint) from public, anon, authenticated;

create or replace function game.enemy_at(p_kind text, idx integer, t bigint, out x double precision, out z double precision, out flying boolean)
 returns record
 language plpgsql
 stable
 set search_path to 'pg_catalog', 'game'
as $$
begin
  if p_kind = 'thug' then
    select * into x, z, flying from game.thug_at(idx, t);
  elsif p_kind = 'rat' then
    select * into x, z, flying from game.rat_at(idx, t);
${Object.entries(ROAMS)
  .map(
    ([kind, r]) => `  elsif p_kind = '${kind}' then
    select * into x, z, flying from game.roam_at(${arr(r.tiles.map((t) => t[0]))},
      ${arr(r.tiles.map((t) => t[1]))}, idx, t, ${r.moveMs}, ${r.walkMs}, ${r.shift});`,
  )
  .join('\n')}
  else
    select * into x, z, flying from game.pigeon_at(idx, t);
  end if;
end $$;
revoke execute on function game.enemy_at(text, integer, bigint) from public, anon, authenticated;`);

// The rows rebuilt from the map.
const masks = walkMasks();
const walkRows = Array.from({ length: GH }, (_, y) => `  (${y}, '${Array.from(masks.slice(y * W, (y + 1) * W), (v) => v.toString(16).padStart(2, '0')).join('')}')`);
const detours = [...allDetours()].map(([k, w]) => `(${k},'{${w.map((p) => p[0]).join(',')}}','{${w.map((p) => p[1]).join(',')}}')`);
say(`
-- ---------- 5. Rebuilt from the map: line of sight, the walk map, the walks round things ----------
truncate game.shot_walls, game.shot_enclosures, game.walk_map, game.roam_paths;
insert into game.shot_walls (x0, y0, x1, y1) values
${SHOT_WALLS.map((r) => `  (${r.x0}, ${r.y0}, ${r.x1}, ${r.y1})`).join(',\n')};
insert into game.shot_enclosures (ord, id, x0, y0, x1, y1) values
${ENCLOSURES.map((e, i) => `  (${i}, '${e.id}', ${e.rect.x0}, ${e.rect.y0}, ${e.rect.x1}, ${e.rect.y1})`).join(',\n')};
-- walk map: ${W} x ${GH}
insert into game.walk_map (y, masks) values
${walkRows.join(',\n')};`);
for (let i = 0; i < detours.length; i += 500) say(`insert into game.roam_paths (fx, fy, tx, ty, xs, ys) values\n${detours.slice(i, i + 500).join(',\n')};`);

// Spots, links, stations.
say(`
-- ---------- 6. The crime spots, the climbing links, the stations ----------
insert into public.spots (id, crime_id, x, y, area_x0, area_y0, area_x1, area_y1) values
${NODES.map((n) => {
  const w = n.wanders;
  return `  ('${n.id}', '${n.crimeId}', ${n.x}, ${n.y}, ${w ? `${w.x0}, ${w.y0}, ${w.x1}, ${w.y1}` : 'null, null, null, null'})`;
}).join(',\n')}
on conflict (id) do update set crime_id = excluded.crime_id, x = excluded.x, y = excluded.y,
  area_x0 = excluded.area_x0, area_y0 = excluded.area_y0, area_x1 = excluded.area_x1, area_y1 = excluded.area_y1;
insert into public.links (id, at_x, at_y, to_x, to_y) values
${LINKS.map((l) => `  ('${l.id}', ${l.at[0]}, ${l.at[1]}, ${l.to[0]}, ${l.to[1]})`).join(',\n')}
on conflict (id) do update set at_x = excluded.at_x, at_y = excluded.at_y, to_x = excluded.to_x, to_y = excluded.to_y;
insert into public.stations (id, kind, x, y) values
${STATIONS.map((s) => `  ('${s.id}', '${s.kind}', ${s.x}, ${s.y})`).join(',\n')}
on conflict (id) do update set kind = excluded.kind, x = excluded.x, y = excluded.y;`);

// The check.
const bar0 = NODES.find((n) => n.id === 'drunk_0')!;
say(`
-- ---------- Check: should say "ok" in every column ----------
select
  case when game.on_map(${W - 1}, ${H - 1}) and not game.on_map(0, ${H}) and game.on_map(${SEWER.x0}, ${SEWER.y0}) and not game.on_map(${SEWER.x0}, ${SEWER.y0 - 1})
    and game.nest_locked(${NEST_GATE[0]}, ${NEST_GATE[1]}) then 'ok' else 'BAD MAP' end as map,
  -- (Nobody in the rock between the island and the sewer, and nobody left where the moved places were.)
  case when (select count(*) from public.players where pos_y between ${H} and ${SEWER.y0 - 1}) = 0
    and (select count(*) from public.players where ${VACATED_RECTS.map((r) => `(pos_x between ${r.x0} and ${r.x1} and pos_y between ${r.y0} and ${r.y1})`).join(' or ')}) = 0 then 'ok' else 'SOMEONE STUCK' end as players,
  case when (select count(*) from public.enemies where kind = 'pigeon') = 8 and (select count(*) from public.spots where crime_id = 'pick_tourist') = 6 then 'ok' else 'BAD PARK' end as park,
  case when (select x from public.spots where id = 'drunk_0') = ${bar0.x} and (select y from public.stations where id = 'barrel_0') = ${STATIONS.find((s) => s.id === 'barrel_0')!.y}
    and (select at_y from public.links where id = 'sewer_up') = ${LINKS.find((l) => l.id === 'sewer_up')!.at[1]} then 'ok' else 'BAD ROWS' end as rows,
  case when (select count(*) from game.walk_map) = ${GH} and (select count(*) from game.roam_paths) = ${detours.length} and (select count(*) from game.shot_walls) = ${SHOT_WALLS.length} then 'ok' else 'BAD TABLES' end as tables,
  case when (select w.x >= ${SEWER.x0} and w.z >= ${SEWER.y0} from game.enemy_at('rat', 0, 1763000000000) w) then 'ok' else 'RATS NOT MOVED' end as rats;

commit;`);
void BAR;
return out.join('\n') + '\n';
}
if (!process.env.VITEST) process.stdout.write(bigMapSql());
