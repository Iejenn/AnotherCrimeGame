// Prints supabase/migrations/0040_beach.sql (v0.57): the walkable beach, the Yard's barrel as a cooking spot, the
// Superstore's parking spot fixed. From the game's map.
// Run: npx vite-node scripts/beach-sql.ts > supabase/migrations/0040_beach.sql
// (src/street/mapSql.test.ts checks the migration is exactly what this prints.)
declare const process: { env: Record<string, string | undefined>; stdout: { write(s: string): void } };
import { GRID, H, NEST, NEST_TUNNEL, NODES, SEWER, STATIONS, W, coastAt } from '../src/street/map';
import { walkMasks } from '../src/street/sight';

export function beachSql(): string {
  const sand: [number, number][] = [];
  for (let y = GRID.y0; y < GRID.y0 + GRID.h; y++) for (let x = GRID.x0; x < GRID.x0 + GRID.w; x++) if (coastAt(x, y) === 'sand') sand.push([x, y]);
  const masks = walkMasks();
  const rows = Array.from({ length: GRID.h }, (_, i) => {
    const y = GRID.y0 + i;
    return `  (${y}, '${Array.from(masks.slice(i * GRID.w, (i + 1) * GRID.w), (v) => v.toString(16).padStart(2, '0')).join('')}')`;
  });
  const spots = NODES.filter((n) => n.id === 'meter_5' || n.id === 'car_4');
  const barrel = STATIONS.find((s) => s.id === 'barrel_1')!;
  const out: string[] = [];
  out.push(`-- 0040_beach (v0.57): you can walk on the beach. GENERATED by scripts/beach-sql.ts from the game's map: don't edit by hand.
--
--  - The beach round the island (the sand of the coast, 1–5 tiles wide) is walkable: game.beach holds its ${sand.length} tiles, and
--    game.on_map (where you may be) includes them. It reads a table now, so it's STABLE instead of IMMUTABLE.
--  - The enemies' walk map covers the beach too: the grid starts at (${GRID.x0}, ${GRID.y0}) now and is ${GRID.w} wide (was 0, 0 and ${W}).
--    game.enemy_route reads it with that offset (rewritten; same signature, same answers on the island).
--  - The Yard's burning barrel is a cooking spot (barrel_1), like the sewer's.
--  - The Superstore's parking spot: the meter stands at the head of the bay (by the store's wall), the car nose-in to it.
--
-- Nothing is deleted except the walk map's rows, rebuilt here. One transaction: to try it first, replace "commit;" at the
-- end with "rollback;". The check should say "ok" in every column.

begin;

create table if not exists game.beach (x smallint not null, y smallint not null, primary key (x, y));
alter table game.beach enable row level security;
revoke all on game.beach from public, anon, authenticated;
truncate game.beach;`);
  for (let i = 0; i < sand.length; i += 600)
    out.push(`insert into game.beach (x, y) values\n${sand.slice(i, i + 600).map(([x, y]) => `(${x},${y})`).join(',')};`);
  out.push(`
create or replace function game.on_map(x integer, y integer)
 returns boolean
 language sql
 stable
 set search_path to 'pg_catalog', 'game'
as $$
  select (x between 0 and ${W - 1} and y between 0 and ${H - 1})
    or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})
    or (x between ${NEST_TUNNEL.x0} and ${NEST_TUNNEL.x1} and y between ${NEST_TUNNEL.y0} and ${NEST_TUNNEL.y1})
    or (x between ${NEST.x0} and ${NEST.x1} and y between ${NEST.y0} and ${NEST.y1})
    or exists (select 1 from game.beach b where b.x = $1 and b.y = $2)
$$;
revoke execute on function game.on_map(integer, integer) from public, anon, authenticated;

-- The walk map: one row per y from ${GRID.y0}, each tile's 8 moves as 2 hex digits from x = ${GRID.x0}.
truncate game.walk_map;
insert into game.walk_map (y, masks) values
${rows.join(',\n')};

-- The route an enemy walks to reach you (the same as enemyRoute in src/street/sight.ts), on the grid with its border:
-- tile (x, y) is grid cell (x - x0, y - y0).
create or replace function game.enemy_route(fx integer, fy integer, tx integer, ty integer)
 returns jsonb
 language plpgsql
 stable
 set search_path to 'pg_catalog', 'game'
as $$
declare
  w constant int := ${GRID.w};
  x0 constant int := ${GRID.x0};
  y0 constant int := ${GRID.y0};
  rows text[] := (select array_agg(masks order by y) from game.walk_map);
  came int[];
  q int[];
  head int := 1;
  dxs constant int[] := array[-1, 0, 1, -1, 1, -1, 0, 1];
  dys constant int[] := array[-1, -1, -1, 0, 0, 1, 1, 1];
  start int := (fy - y0) * w + (fx - x0);
  c int; cx int; cy int; m int; i int; n int; nx int; ny int; k int;
  route jsonb := '[]'::jsonb;
begin
  if rows is null or fy - y0 < 0 or fy - y0 >= cardinality(rows) or fx - x0 < 0 or fx - x0 >= w then return null; end if;
  -- Already next to you (and able to step onto your tile).
  if greatest(abs(fx - tx), abs(fy - ty)) = 1
     and (('x' || substr(rows[fy - y0 + 1], (fx - x0) * 2 + 1, 2))::bit(8)::int & (1 << game.walk_bit(tx - fx, ty - fy))) <> 0 then
    return route;
  end if;
  came := array_fill(-1, array[w * cardinality(rows)]);
  came[start + 1] := start;
  q := array[start];
  while head <= cardinality(q) loop
    c := q[head];
    head := head + 1;
    cx := c % w + x0;
    cy := c / w + y0;
    m := ('x' || substr(rows[cy - y0 + 1], (cx - x0) * 2 + 1, 2))::bit(8)::int;
    for i in 1..8 loop
      continue when (m & (1 << (i - 1))) = 0;
      nx := cx + dxs[i];
      ny := cy + dys[i];
      n := (ny - y0) * w + (nx - x0);
      continue when came[n + 1] >= 0;
      came[n + 1] := c;
      if greatest(abs(nx - tx), abs(ny - ty)) = 1
         and (('x' || substr(rows[ny - y0 + 1], (nx - x0) * 2 + 1, 2))::bit(8)::int & (1 << game.walk_bit(tx - nx, ty - ny))) <> 0 then
        k := n;
        while k <> start loop
          route := jsonb_build_array(jsonb_build_array(k % w + x0, k / w + y0)) || route;
          k := came[k + 1];
        end loop;
        return route;
      end if;
      q := array_append(q, n);
    end loop;
  end loop;
  return null;
end $$;
revoke execute on function game.enemy_route(integer, integer, integer, integer) from public, anon, authenticated;

insert into public.stations (id, kind, x, y) values ('${barrel.id}', '${barrel.kind}', ${barrel.x}, ${barrel.y})
on conflict (id) do update set kind = excluded.kind, x = excluded.x, y = excluded.y;
insert into public.spots (id, crime_id, x, y, area_x0, area_y0, area_x1, area_y1) values
${spots.map((s) => `  ('${s.id}', '${s.crimeId}', ${s.x}, ${s.y}, null, null, null, null)`).join(',\n')}
on conflict (id) do update set x = excluded.x, y = excluded.y;

-- ---------- Check: should say "ok" in every column ----------
select
  case when (select count(*) from game.beach) = ${sand.length} and game.on_map(${sand[0][0]}, ${sand[0][1]}) and not game.on_map(${GRID.x0}, ${GRID.y0})
    and game.on_map(0, 0) then 'ok' else 'BAD BEACH' end as beach,
  case when (select count(*) from game.walk_map) = ${GRID.h} and (select min(y) from game.walk_map) = ${GRID.y0} then 'ok' else 'BAD WALK MAP' end as walk_map,
  case when exists (select 1 from public.stations where id = 'barrel_1') and (select y from public.spots where id = 'meter_5') = ${spots.find((s) => s.id === 'meter_5')!.y} then 'ok' else 'BAD ROWS' end as rows;

commit;
`);
  return out.join('\n');
}
if (!process.env.VITEST) process.stdout.write(beachSql());
