// Prints supabase/migrations/0040_beach.sql (v0.57): the walkable beach, the Yard's barrel as a cooking spot, the
// Superstore's parking spot fixed. From the game's map.
// Run: npx vite-node scripts/beach-sql.ts > supabase/migrations/0040_beach.sql
// (src/street/mapSql.test.ts checks the migration is exactly what this prints.)
declare const process: { env: Record<string, string | undefined>; stdout: { write(s: string): void } };
import { GH, GRID, H, NEST, NEST_TUNNEL, NODES, SEWER, STATIONS, W, coastAt, gi } from '../src/street/map';
import { walkMasks } from '../src/street/sight';

/** The beach as stretches of sand: per row, from x0 to x1 (a row of the north or south beach is one stretch, a row
 *  beside the city two). */
export function beachRows(): [number, number, number][] {
  const out: [number, number, number][] = [];
  for (let y = GRID.y0; y < GRID.y0 + GRID.h; y++) {
    let start: number | null = null;
    for (let x = GRID.x0; x <= GRID.x0 + GRID.w; x++) {
      const sand = x < GRID.x0 + GRID.w && coastAt(x, y) === 'sand';
      if (sand && start === null) start = x;
      if (!sand && start !== null) out.push([y, start, x - 1]), (start = null);
    }
  }
  return out;
}

/** The enemies' walk map rows (y 0 and up, x 0 to W) that aren't what the live one has (live: 0038, which rebuilt it). */
export function changedWalkRows(live: string): [number, string][] {
  const m = walkMasks();
  const out: [number, string][] = [];
  for (let y = 0; y < GH; y++) {
    const row = Array.from({ length: W }, (_, x) => m[gi(x, y)].toString(16).padStart(2, '0')).join('');
    if (!live.includes(`  (${y}, '${row}')`)) out.push([y, row]);
  }
  return out;
}

/** live: the text of 0038 (the walk map that's live). */
export function beachSql(live: string): string {
  const rows = beachRows();
  const walk = changedWalkRows(live);
  const spots = NODES.filter((n) => n.id === 'meter_5' || n.id === 'car_4');
  const barrel = STATIONS.find((s) => s.id === 'barrel_1')!;
  const [y, x0] = rows[0];
  return `-- 0040_beach (v0.57): you can walk on the beach. GENERATED by scripts/beach-sql.ts from the game's map.
--  - The beach round the island is walkable: game.beach holds its sand as ${rows.length} stretches (a row, from x0 to x1),
--    and game.on_map (where you may be) includes them. It reads a table now, so it's STABLE instead of IMMUTABLE.
--    (Enemies keep off the sand, so their walk map doesn't change.)
--  - The Yard's burning barrel is a cooking spot (barrel_1), like the sewer's.
--  - The Superstore's parking spot: the meter at the head of the bay (by the store's wall), the car nose-in to it; and the
--    ${walk.length} rows of the enemies' walk map round it that this changes.
-- Nothing is deleted. One transaction: to try it first, replace "commit;" with "rollback;". The check should say "ok".

begin;

create table if not exists game.beach (y smallint not null, x0 smallint not null, x1 smallint not null, primary key (y, x0));
alter table game.beach enable row level security;
revoke all on game.beach from public, anon, authenticated;
truncate game.beach;
insert into game.beach (y, x0, x1) values
${rows.map(([ry, a, b]) => `(${ry},${a},${b})`).join(',')};

create or replace function game.on_map(x integer, y integer)
 returns boolean
 language sql
 stable
 set search_path to 'pg_catalog', 'game'
as $$
  select (x between 0 and ${W - 1} and y between 0 and ${H - 1})
    or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})
    or (x between ${NEST_TUNNEL.x0} and ${NEST_TUNNEL.x1} and y between ${NEST_TUNNEL.y0} and ${NEST_TUNNEL.y1})
    or (x between ${NEST.x0} and ${NEST.x1} and y between ${NEST.y0} and ${NEST.y1})
    or exists (select 1 from game.beach b where b.y = $2 and $1 between b.x0 and b.x1)
$$;
revoke execute on function game.on_map(integer, integer) from public, anon, authenticated;

insert into public.stations (id, kind, x, y) values ('${barrel.id}', '${barrel.kind}', ${barrel.x}, ${barrel.y})
on conflict (id) do update set kind = excluded.kind, x = excluded.x, y = excluded.y;
insert into public.spots (id, crime_id, x, y, area_x0, area_y0, area_x1, area_y1) values
${spots.map((s) => `  ('${s.id}', '${s.crimeId}', ${s.x}, ${s.y}, null, null, null, null)`).join(',\n')}
on conflict (id) do update set x = excluded.x, y = excluded.y;
${walk.map(([wy, r]) => `update game.walk_map set masks = '${r}' where y = ${wy};`).join('\n')}

select
  case when (select count(*) from game.beach) = ${rows.length} and game.on_map(${x0}, ${y}) and not game.on_map(${GRID.x0}, ${GRID.y0})
    and game.on_map(0, 0) then 'ok' else 'BAD BEACH' end as beach,
  case when exists (select 1 from public.stations where id = 'barrel_1')
    and (select y from public.spots where id = 'meter_5') = ${spots.find((s) => s.id === 'meter_5')!.y} then 'ok' else 'BAD ROWS' end as rows;

commit;
`;
}
declare const require: (m: string) => { readFileSync(p: string, e: string): string };
if (!process.env.VITEST) process.stdout.write(beachSql(require('node:fs').readFileSync('supabase/migrations/0038_aluminium.sql', 'utf8')));
