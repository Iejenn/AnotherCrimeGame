// Writes supabase/migrations/0026_zone_west.sql: the Industrial zone moves to the west side of the city (v0.41). In tile
// coordinates the city moves CITY_X tiles east and the zone (the Factory) CITY_X tiles west; the sewer stays where it is.
// Every position the server keeps or knows (players, graves, ground items, spots, stations, the pothole, the spawn, the
// hospital, the shops' areas, the guard's route, the Pigeons' and thugs' tiles) moves with it. GENERATED from the game's
// data, so the new numbers are the game's own; the old ones are the new ones moved back, checked against the live functions.
// Run: npx vite-node scripts/zone-west-sql.ts
import { writeFileSync } from 'node:fs';
import { CITY_X, H, SPAWN, STATIONS, STORE, WAKE, WEAPONS } from '../src/street/map';
import { PIGEON_TILES, THUG_TILES } from '../src/game/enemies';
import { GUARD_ROUTE } from '../src/game/watchers';

const D = CITY_X;
const lit = (s: string) => `E'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const arr = (xs: number[], sep = ',') => `array[${xs.join(sep)}]`;
/** The same text before and after: [old (city where it was), new]. */
const both = (f: (shift: number) => string): [string, string] => [f(-D), f(0)];

const swaps: [string, string, string][] = [
  ['game.can_reach(public.players, integer, integer)', ...both((s) => `coalesce(p.pos_x, ${SPAWN[0] + s})`)],
  ['game.world(uuid)', ...both((s) => `coalesce(w.from_x, p.pos_x, ${SPAWN[0] + s})`)],
  ['game.die(public.players, timestamp with time zone, jsonb, jsonb)', ...both((s) => `p.pos_x := ${WAKE[0] + s}; p.pos_y := ${WAKE[1]};`)],
  ['game.die(public.players, timestamp with time zone, jsonb, jsonb)', ...both((s) => `set from_x = ${WAKE[0] + s}, from_y = ${WAKE[1]},`)],
  ['public.buy_item(text)', ...both((s) => `p.pos_x between ${WEAPONS.x0 + s} and ${WEAPONS.x1 + s} and p.pos_y between ${WEAPONS.y0} and ${WEAPONS.y1}`)],
  ['public.sell_item(text)', ...both((s) => `p.pos_x between ${WEAPONS.x0 + s} and ${WEAPONS.x1 + s} else p.pos_x between ${STORE.x0 + s} and ${STORE.x1 + s} end`)],
  ['game.guard_at(bigint)', ...both((s) => `rx int[] := ${arr(GUARD_ROUTE.map(([x]) => x + s), ', ')};`)],
  ['game.pigeon_at(integer, bigint)', ...both((s) => `px int[] := ${arr(PIGEON_TILES.map(([x]) => x + s))};`)],
  ['game.thug_at(integer, bigint)', ...both((s) => `px int[] := ${arr(THUG_TILES.map(([x]) => x + s))};`)],
];

const city = `y < ${H}`; // on the island (the sewer is below it, y ≥ ${H}, and doesn't move)
const zoneStations = STATIONS.filter((s) => s.kind === 'press' || s.kind === 'bench');

const sql = `-- 0026: the Industrial zone moves to the WEST of the city (docs/design.md §14). GENERATED by scripts/zone-west-sql.ts.
--
-- ⚠ CHANGES PLAYER DATA (on purpose, nobody loses anything): in tile coordinates the city moves ${D} tiles east (the
-- zone takes its old place), so every saved position on the island moves ${D} tiles east with it: where players stand,
-- graves, things on the ground, the crime spots, the barbecue, the pothole. The Factory's presses and workbenches move
-- ${D} tiles west. The sewer doesn't move. Attempts and fights in progress stop, and walking routes are cleared (like when
-- the city was rebuilt, 0013). In the functions: the spawn, the hospital's wake tile, Eddy's and Ray's areas, the guard's
-- route, the Pigeons' and thugs' tiles (each swapped in its live definition; it stops if one isn't found).
-- It all runs in one transaction: if anything goes wrong, nothing is changed.
-- DRY RUN: change the last line "commit;" to "rollback;", run it, look at the result, then run it again with "commit;".
-- Run it right before merging: the game must move at the same time as the server.

begin;

-- ---------- what's stored ----------
update public.players set pos_x = pos_x + ${D} where pos_x is not null and pos_${city};
update public.players set job_crime = null, job_spot = null, job_started_at = null, job_ends_at = null, job_pos_x = null, job_pos_y = null,
  caught_crime = null, caught_at = null, fight_enemy = null;
update public.enemies set fighter = null;
update public.enemies set fight_x = fight_x + ${D} where fight_x is not null and fight_${city};
update public.enemies set left_x = left_x + ${D} where left_x is not null and left_${city};
update public.graves set x = x + ${D} where ${city};
update public.ground_items set x = x + ${D} where ${city};
update public.spots set x = x + ${D}, area_x0 = area_x0 + ${D}, area_x1 = area_x1 + ${D};
update public.stations set x = x + ${D} where kind = 'bbq' and ${city};
update public.stations set x = x - ${D} where kind in ('press', 'bench');
update public.links set at_x = at_x + ${D} where at_${city};
update public.links set to_x = to_x + ${D} where to_${city};
delete from public.walks;

-- ---------- the functions that know places ----------
do $do$
declare
  r record;
  def text;
begin
  for r in select * from (values
${swaps.map(([fn, a, b]) => `    ('${fn}', ${lit(a)}, ${lit(b)})`).join(',\n')}
  ) as t(fn, old_text, new_text) loop
    def := pg_get_functiondef(r.fn::regprocedure);
    if position(r.old_text in def) = 0 then raise exception '%: anchor not found: %', r.fn, r.old_text; end if;
    execute replace(def, r.old_text, r.new_text);
  end loop;
end $do$;

-- Check: the stations and spots are where the game has them (stops and undoes everything if not).
do $do$
begin
  if not exists (select 1 from public.stations where id = '${zoneStations[0].id}' and x = ${zoneStations[0].x} and y = ${zoneStations[0].y})
     or not exists (select 1 from public.stations where id = 'bbq_0' and x = ${STATIONS.find((s) => s.id === 'bbq_0')!.x}) then
    raise exception 'stations are not where the game has them: nothing was changed';
  end if;
end $do$;
select (select count(*) from public.players where pos_x is not null and pos_${city}) as players_on_the_island,
  (select x || ',' || y from public.stations where id = 'bbq_0') as barbecue,
  (select at_x || ',' || at_y from public.links where id = 'sewer_down') as pothole;

commit;
`;
writeFileSync(new URL('../supabase/migrations/0026_zone_west.sql', import.meta.url), sql);
console.log(`wrote 0026_zone_west.sql (${sql.length} bytes)`);
for (const [fn, a] of swaps) console.log(fn, '|', a.slice(0, 80));
