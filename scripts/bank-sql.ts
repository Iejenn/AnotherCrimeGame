// Writes supabase/migrations/0027_bank.sql: the Financial district (the map is wider) and the bank (docs/design.md §15),
// from the game's data (map.ts), so the server's bank area and slot count can't disagree with the game.
// Run: npx vite-node scripts/bank-sql.ts
import { writeFileSync } from 'node:fs';
import { BANK, BANK_SLOTS, H, SEWER, W } from '../src/street/map';

const lit = (s: string) => `E'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const inBank = (x: string, y: string) => `${x} between ${BANK.x0} and ${BANK.x1} and ${y} between ${BANK.y0} and ${BANK.y1}`;

/** The checks every bank move starts with: your character, you're really standing in the bank. */
const start = `  if p.id is null then return jsonb_build_object('ok', false, 'reason', 'no_character'); end if;
  if not game.can_reach(p, p_x, p_y) then return game.respond(p.id, false, 'too_fast', null, null); end if;
  if not (${inBank('p_x', 'p_y')}) then return game.respond(p.id, false, 'not_in_bank', null, null); end if;`;

const sql = `-- 0027: the Financial district and the bank (docs/design.md §15). GENERATED by scripts/bank-sql.ts.
--
--  - game.on_map: the map is ${W} tiles wide now (the Financial district east of the city; nothing else moves).
--  - players.bank: what's in your bank, in the order you first put it in: [{"i": item, "n": how many}, …] (things stack
--    here); players.bank_cash: the cash you keep there. Both are safe when you die (the grave only takes your bag and
--    the cash in your pocket).
--  - bank_deposit(item, n, x, y), bank_withdraw(item, n, x, y), bank_deposit_all(x, y): only while you stand in the
--    bank (x ${BANK.x0}–${BANK.x1}, y ${BANK.y0}–${BANK.y1}); 'cash' moves dollars. ${BANK_SLOTS} slots (different things; cash counts as one);
--    taking things out only takes as many as fit in your bag (game.bag_slots).
--  - game.respond sends your bank along.
-- Additive: new columns and functions, one changed line in respond. No data is changed.

create or replace function game.on_map(x int, y int) returns boolean
language sql immutable set search_path = pg_catalog as $$
  select (x between 0 and ${W - 1} and y between 0 and ${H - 1}) or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})
$$;
revoke execute on function game.on_map(int, int) from public, anon, authenticated;

alter table public.players add column if not exists bank jsonb not null default '[]'::jsonb;
alter table public.players add column if not exists bank_cash bigint not null default 0;

-- How many different things fit in the bank (cash counts as one).
create or replace function game.bank_slots() returns int
language sql immutable set search_path = pg_catalog as $$ select ${BANK_SLOTS} $$;
revoke execute on function game.bank_slots() from public, anon, authenticated;

-- How many slots the bank uses.
create or replace function game.bank_used(b jsonb, b_cash bigint) returns int
language sql immutable set search_path = pg_catalog as $$ select jsonb_array_length(b) + case when b_cash > 0 then 1 else 0 end $$;
revoke execute on function game.bank_used(jsonb, bigint) from public, anon, authenticated;

-- Put n of something in the bank ('cash': n dollars). It moves as many as you have.
create or replace function public.bank_deposit(p_item text, p_n int, p_x int, p_y int)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  have int;
  k bigint;
  idx int;
begin
${start}
  if p_n is null or p_n < 1 then return game.respond(p.id, false, 'nothing_there', null, null); end if;
  if p_item = 'cash' then
    k := least(p_n::bigint, p.cash);
    if k <= 0 then return game.respond(p.id, false, 'nothing_there', null, null); end if;
    if p.bank_cash = 0 and game.bank_used(p.bank, 0) >= game.bank_slots() then return game.respond(p.id, false, 'bank_full', null, null); end if;
    update public.players set cash = cash - k, bank_cash = bank_cash + k, updated_at = now() where id = p.id;
    return game.respond(p.id, true, null, null, null);
  end if;
  have := coalesce((p.inventory ->> p_item)::int, 0);
  k := least(p_n, have);
  if k <= 0 then return game.respond(p.id, false, 'nothing_there', null, null); end if;
  select (e.ord - 1)::int into idx from jsonb_array_elements(p.bank) with ordinality as e(v, ord) where e.v ->> 'i' = p_item;
  if idx is null then
    if game.bank_used(p.bank, p.bank_cash) >= game.bank_slots() then return game.respond(p.id, false, 'bank_full', null, null); end if;
    p.bank := p.bank || jsonb_build_array(jsonb_build_object('i', p_item, 'n', k));
  else
    p.bank := jsonb_set(p.bank, array[idx::text, 'n'], to_jsonb((p.bank -> idx ->> 'n')::bigint + k));
  end if;
  p.inventory := case when have = k then p.inventory - p_item else jsonb_set(p.inventory, array[p_item], to_jsonb(have - k)) end;
  update public.players set inventory = p.inventory, bank = p.bank, updated_at = now() where id = p.id;
  return game.respond(p.id, true, null, null, null);
end $$;
grant execute on function public.bank_deposit(text, int, int, int) to authenticated;
revoke execute on function public.bank_deposit(text, int, int, int) from public, anon;

-- Take n of something out ('cash': n dollars). Items: only as many as fit in your bag.
create or replace function public.bank_withdraw(p_item text, p_n int, p_x int, p_y int)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  idx int;
  have bigint;
  k bigint;
begin
${start}
  if p_n is null or p_n < 1 then return game.respond(p.id, false, 'nothing_there', null, null); end if;
  if p_item = 'cash' then
    k := least(p_n::bigint, p.bank_cash);
    if k <= 0 then return game.respond(p.id, false, 'nothing_there', null, null); end if;
    update public.players set cash = cash + k, bank_cash = bank_cash - k, updated_at = now() where id = p.id;
    return game.respond(p.id, true, null, null, null);
  end if;
  select (e.ord - 1)::int, (e.v ->> 'n')::bigint into idx, have from jsonb_array_elements(p.bank) with ordinality as e(v, ord) where e.v ->> 'i' = p_item;
  if idx is null then return game.respond(p.id, false, 'nothing_there', null, null); end if;
  k := least(p_n::bigint, have, game.bag_slots() - game.bag_used(p.inventory));
  if k <= 0 then return game.respond(p.id, false, 'bag_full', null, null); end if;
  p.bank := case when k = have then p.bank - idx else jsonb_set(p.bank, array[idx::text, 'n'], to_jsonb(have - k)) end;
  p.inventory := jsonb_set(p.inventory, array[p_item], to_jsonb(coalesce((p.inventory ->> p_item)::int, 0) + k));
  update public.players set inventory = p.inventory, bank = p.bank, updated_at = now() where id = p.id;
  return game.respond(p.id, true, null, null, null);
end $$;
grant execute on function public.bank_withdraw(text, int, int, int) to authenticated;
revoke execute on function public.bank_withdraw(text, int, int, int) from public, anon;

-- Put your whole bag in (your cash too). What doesn't fit (a new kind of thing when the bank is full) stays in your bag.
create or replace function public.bank_deposit_all(p_x int, p_y int)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  r record;
  idx int;
  full_up boolean := false;
begin
${start}
  if p.cash > 0 then
    if p.bank_cash > 0 or game.bank_used(p.bank, 0) < game.bank_slots() then
      p.bank_cash := p.bank_cash + p.cash;
      p.cash := 0;
    else
      full_up := true;
    end if;
  end if;
  for r in select key, value::int as n from jsonb_each_text(p.inventory) loop
    idx := null;
    select (e.ord - 1)::int into idx from jsonb_array_elements(p.bank) with ordinality as e(v, ord) where e.v ->> 'i' = r.key;
    if idx is null then
      if game.bank_used(p.bank, p.bank_cash) >= game.bank_slots() then full_up := true; continue; end if;
      p.bank := p.bank || jsonb_build_array(jsonb_build_object('i', r.key, 'n', r.n));
    else
      p.bank := jsonb_set(p.bank, array[idx::text, 'n'], to_jsonb((p.bank -> idx ->> 'n')::bigint + r.n));
    end if;
    p.inventory := p.inventory - r.key;
  end loop;
  update public.players set inventory = p.inventory, cash = p.cash, bank = p.bank, bank_cash = p.bank_cash, updated_at = now() where id = p.id;
  return game.respond(p.id, true, case when full_up then 'bank_full' end, null, null);
end $$;
grant execute on function public.bank_deposit_all(int, int) to authenticated;
revoke execute on function public.bank_deposit_all(int, int) from public, anon;

do $do$
declare def text;
begin
  def := pg_get_functiondef('game.respond(uuid, boolean, text, jsonb, jsonb)'::regprocedure);
  if position(${lit("'inventory', p.inventory, 'stats', p.stats,")} in def) = 0 then raise exception 'respond: anchor not found'; end if;
  execute replace(def, ${lit("'inventory', p.inventory, 'stats', p.stats,")}, ${lit("'inventory', p.inventory, 'bank', p.bank, 'bankCash', p.bank_cash, 'stats', p.stats,")});
end $do$;

-- Check: this should say "ok".
select case when game.on_map(${W - 1}, 10) and game.bank_slots() = ${BANK_SLOTS}
  and position('bankCash' in pg_get_functiondef('game.respond(uuid, boolean, text, jsonb, jsonb)'::regprocedure)) > 0
  then 'ok' else 'NOT APPLIED' end as bank;
`;
writeFileSync(new URL('../supabase/migrations/0027_bank.sql', import.meta.url), sql);
console.log(`wrote 0027_bank.sql (${sql.length} bytes); the bank is x ${BANK.x0}-${BANK.x1}, y ${BANK.y0}-${BANK.y1}; W ${W}`);
