// Prints supabase/migrations/0038_aluminium.sql (v0.56): the aluminium tier and the Superstore, from the game's data.
// Run: npx vite-node scripts/aluminium-sql.ts > supabase/migrations/0038_aluminium.sql
// (src/street/mapSql.test.ts checks the migration is exactly what this prints.)
declare const process: { env: Record<string, string | undefined>; stdout: { write(s: string): void } };
import { CRAFTS, METAL_ITEMS } from '../src/game/data/metals';
import { SHOPS } from '../src/game/data/items';
import { CRIME_BY_ID } from '../src/game/data/crimes';
import { ENCLOSURES, GH, NODES, W } from '../src/street/map';
import { SHOT_WALLS, walkMasks } from '../src/street/sight';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const n = (v: number | undefined | null) => (v === undefined || v === null ? 'null' : String(v));

/** The public.items rows of a metal (the same columns and values as the live copper rows: a test checks that). */
export function metalItemRows(metal: string) {
  return METAL_ITEMS.filter((i) => i.id.startsWith(`${metal}_`)).map((i) => {
    const g = i.gear;
    return `  (${q(i.id)}, ${q(i.name)}, ${g ? q(g.slot) : 'null'}, ${g?.damage ?? 0}, ${g?.accuracy ?? 0}, ${g?.defence ?? 0}, ${n(g?.speed)}, ${g?.needs ? q(g.needs.skill) : 'null'}, ${g?.needs?.level ?? 1}, ${i.heal}, ${i.value}, ${i.quest ? 'true' : 'false'}, ${i.stack ? 'true' : 'false'}, ${n(g?.range)})`;
  });
}

export function aluminiumSql(): string {
  const crafts = CRAFTS.filter((c) => c.id.startsWith('aluminium_'));
  const shop = SHOPS.weapons.filter((s) => s.item.startsWith('aluminium_'));
  const crime = CRIME_BY_ID.aluminium_salvage;
  const spots = NODES.filter((nd) => nd.crimeId === 'aluminium_salvage' || nd.id === 'meter_5' || nd.id === 'car_4');
  const masks = walkMasks();
  return `-- 0038_aluminium (v0.56): the aluminium tier and the Superstore. GENERATED by scripts/aluminium-sql.ts from the game's
-- data: don't edit by hand.
--
--  - Aluminium (tier 3, level 21): salvage, sheets and the six pieces plus throwing knives, with the same formulas as tin
--    and copper (items, crafts at the Factory's press and benches, Ray's weapons).
--  - Aluminium Salvaging (Scrapping 21, 35%, 20 XP): five dumpsters in the Superstore's yard (F-013-B).
--  - The Superstore's little parking spot (F-013-A): one more meter (meter_5) and one more car (car_4).
--  - The map's walls, enclosures and walk map, rebuilt (the Superstore, its walled yard).
--
-- Additive: new rows (updated if they exist), the three map tables rebuilt from the map. No player data is changed.
-- One transaction: to try it first, replace "commit;" at the end with "rollback;". The check should say "ok".

begin;

insert into public.items (id, name, slot, damage, accuracy, defence, speed, needs_skill, needs_level, heal, value, quest, stack, range) values
${metalItemRows('aluminium').join(',\n')}
on conflict (id) do update set name = excluded.name, slot = excluded.slot, damage = excluded.damage, accuracy = excluded.accuracy,
  defence = excluded.defence, speed = excluded.speed, needs_skill = excluded.needs_skill, needs_level = excluded.needs_level,
  heal = excluded.heal, value = excluded.value, quest = excluded.quest, stack = excluded.stack, range = excluded.range;

insert into public.crafts (id, station_kind, skill, level, xp, ticks, inputs, amount) values
${crafts.map((c) => `  (${q(c.id)}, ${q(c.station)}, ${q(c.skill)}, ${c.level}, ${c.xp}, ${c.ticks}, ${q(JSON.stringify(c.inputs))}::jsonb, ${c.amount ?? 1})`).join(',\n')}
on conflict (id) do update set station_kind = excluded.station_kind, skill = excluded.skill, level = excluded.level, xp = excluded.xp,
  ticks = excluded.ticks, inputs = excluded.inputs, amount = excluded.amount;

insert into public.shop_items (shop, item, price, amount) values
${shop.map((s) => `  ('weapons', ${q(s.item)}, ${s.price}, ${s.amount})`).join(',\n')}
on conflict (shop, item) do update set price = excluded.price, amount = excluded.amount;

insert into public.crimes (id, name, level, ticks, base_chance, xp, cash_min, cash_max, items, fail_damage, fail_stun, catcher, refill, skill)
values (${q(crime.id)}, ${q(crime.name)}, ${crime.level}, ${crime.ticks}, ${crime.baseChance}, ${crime.xp}, ${crime.cashMin}, ${crime.cashMax},
  array[${(crime.items ?? []).map(q).join(', ')}]::text[], ${crime.failDamage}, ${crime.failStun}, ${crime.catcher ? q(crime.catcher) : 'null'}, ${crime.refill ?? 'null'}, ${q(crime.skill)})
on conflict (id) do update set name = excluded.name, level = excluded.level, ticks = excluded.ticks, base_chance = excluded.base_chance,
  xp = excluded.xp, cash_min = excluded.cash_min, cash_max = excluded.cash_max, items = excluded.items, fail_damage = excluded.fail_damage,
  fail_stun = excluded.fail_stun, catcher = excluded.catcher, refill = excluded.refill, skill = excluded.skill;

insert into public.spots (id, crime_id, x, y, area_x0, area_y0, area_x1, area_y1) values
${spots.map((s) => `  (${q(s.id)}, ${q(s.crimeId)}, ${s.x}, ${s.y}, null, null, null, null)`).join(',\n')}
on conflict (id) do update set crime_id = excluded.crime_id, x = excluded.x, y = excluded.y,
  area_x0 = excluded.area_x0, area_y0 = excluded.area_y0, area_x1 = excluded.area_x1, area_y1 = excluded.area_y1;

-- The map tables, rebuilt from the map (the Superstore and its yard are new).
truncate game.shot_walls, game.shot_enclosures, game.walk_map;
insert into game.shot_walls (x0, y0, x1, y1) values
${SHOT_WALLS.map((r) => `  (${r.x0}, ${r.y0}, ${r.x1}, ${r.y1})`).join(',\n')};
insert into game.shot_enclosures (ord, id, x0, y0, x1, y1) values
${ENCLOSURES.map((e, i) => `  (${i}, '${e.id}', ${e.rect.x0}, ${e.rect.y0}, ${e.rect.x1}, ${e.rect.y1})`).join(',\n')};
insert into game.walk_map (y, masks) values
${Array.from({ length: GH }, (_, y) => `  (${y}, '${Array.from(masks.slice(y * W, (y + 1) * W), (v) => v.toString(16).padStart(2, '0')).join('')}')`).join(',\n')};

-- ---------- Check: should say "ok" in every column ----------
select
  case when (select count(*) from public.items where id like 'aluminium_%') = ${METAL_ITEMS.filter((i) => i.id.startsWith('aluminium_')).length}
    and (select count(*) from public.crafts where id like 'aluminium_%') = ${crafts.length}
    and (select count(*) from public.shop_items where item like 'aluminium_%') = ${shop.length} then 'ok' else 'ITEMS MISSING' end as items,
  case when (select level from public.crimes where id = 'aluminium_salvage') = ${crime.level}
    and (select count(*) from public.spots where crime_id = 'aluminium_salvage') = ${spots.filter((s) => s.crimeId === 'aluminium_salvage').length}
    and exists (select 1 from public.spots where id = 'car_4') and exists (select 1 from public.spots where id = 'meter_5') then 'ok' else 'SPOTS MISSING' end as spots,
  case when (select count(*) from game.walk_map) = ${GH} and (select count(*) from game.shot_walls) = ${SHOT_WALLS.length}
    and (select count(*) from game.shot_enclosures) = ${ENCLOSURES.length} then 'ok' else 'BAD MAP TABLES' end as map;

commit;
`;
}
if (!process.env.VITEST) process.stdout.write(aluminiumSql());
