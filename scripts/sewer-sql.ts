// Writes supabase/migrations/0019_sewer.sql from the game's data (src/street/map.ts, src/game/enemies.ts, items.ts,
// recipes.ts), so the server's sewer (where you may stand, the pothole/ladder links, the rats and their schedule, rat
// meat and its recipe) can't disagree with the game.
// Run: npx vite-node scripts/sewer-sql.ts
import { writeFileSync } from 'node:fs';
import { H, LINKS, SEWER, W } from '../src/street/map';
import { ENEMIES, ENEMY_KINDS, RAT_MOVE_MS, RAT_WALK_MS, RAT_ZONES } from '../src/game/enemies';
import { ITEM_BY_ID } from '../src/game/data/items';
import { RECIPE_BY_ITEM } from '../src/game/data/recipes';

const k = ENEMY_KINDS.rat;
const rats = ENEMIES.filter((e) => e.kind === 'rat');
const tiles = RAT_ZONES.flat();
const starts: number[] = [];
let at = 1;
for (const z of RAT_ZONES) starts.push(at), (at += z.length);
const raw = ITEM_BY_ID.raw_rat_meat;
const cooked = ITEM_BY_ID.cooked_rat_meat;
const rc = RECIPE_BY_ITEM.raw_rat_meat;
const onMapSql = `(x between 0 and ${W - 1} and y between 0 and ${H - 1}) or (x between ${SEWER.x0} and ${SEWER.x1} and y between ${SEWER.y0} and ${SEWER.y1})`;

const sql = `-- 0019: the sewer and its rats (docs/design.md §12). GENERATED by scripts/sewer-sql.ts.
--
-- The sewer is a strip of tiles below the island's grid (x ${SEWER.x0}–${SEWER.x1}, y ${SEWER.y0}–${SEWER.y1}). You get in through the pothole in the
-- crossing east of the candy shop and out by its ladder: climb() moves you (it checks you stand next to it).
--  - game.on_map(x, y): the island or the sewer. walk() and can_reach() used "0..57" for both; now they use this.
--  - links: the pothole (down) and the ladder (up). climb(link, x, y) ends a fight, cooking or an attempt, like walking off.
--  - enemy_kinds: the rat (level ${k.level}, ${k.hp} HP, attack ${k.attack}, defence ${k.defense}, max hit ${k.maxHit}, a bite every ${k.speed} ticks, back
--    ${k.respawn} s after a kill, not aggressive). enemies: rat_0..rat_${rats.length - 1}. loot: raw rat meat, always.
--  - items: raw rat meat ($${raw.value}), cooked rat meat (+${cooked.heal} HP, $${cooked.value}); recipes: raw → cooked at the barbecue (like bird meat).
--  - game.rat_at: where rat idx is at time t (each in its own patch of a walkway; a new spot every ${RAT_MOVE_MS / 1000} s, ${RAT_WALK_MS / 1000} s to
--    scurry there), the same as ratAt() in src/game/enemies.ts. game.enemy_at learns rats.
-- Additive: new rows, a new table, new functions, and the bounds line in walk and can_reach (swapped in their live
-- definitions; it stops if a line isn't found). No player data is changed.

-- ---------- where you may be ----------
create or replace function game.on_map(x int, y int) returns boolean
language sql immutable set search_path = pg_catalog as $$
  select ${onMapSql}
$$;
revoke execute on function game.on_map(int, int) from public, anon, authenticated;

do $do$
declare def text;
begin
  def := pg_get_functiondef('game.can_reach(public.players, integer, integer)'::regprocedure);
  if position('x between 0 and 57 and y between 0 and 57' in def) = 0 then raise exception 'can_reach: anchor not found'; end if;
  def := replace(def, 'x between 0 and 57 and y between 0 and 57', 'game.on_map(x, y)');
  execute def;
  def := pg_get_functiondef('public.walk(integer, integer, jsonb)'::regprocedure);
  if position('sx not between 0 and 57 or sy not between 0 and 57' in def) = 0 then raise exception 'walk: anchor not found'; end if;
  def := replace(def, 'sx not between 0 and 57 or sy not between 0 and 57', 'not game.on_map(sx, sy)');
  execute def;
end $do$;

-- ---------- climbing: the pothole and the ladder ----------
create table if not exists public.links (
  id text primary key,
  at_x int not null, at_y int not null,   -- stand on it or next to it
  to_x int not null, to_y int not null    -- where you come out
);
alter table public.links enable row level security;
insert into public.links (id, at_x, at_y, to_x, to_y) values
${LINKS.map((l) => `  ('${l.id}', ${l.at[0]}, ${l.at[1]}, ${l.to[0]}, ${l.to[1]})`).join(',\n')}
on conflict (id) do update set at_x = excluded.at_x, at_y = excluded.at_y, to_x = excluded.to_x, to_y = excluded.to_y;

create or replace function public.climb(p_link text, p_x int, p_y int)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, game as $$
declare
  p public.players := game.me();
  rep jsonb := game.empty_report();
  logs jsonb := '[]'::jsonb;
  r record;
  l public.links;
begin
  if p.id is null then return jsonb_build_object('ok', false, 'reason', 'no_character'); end if;
  select * into r from game.settle(p, rep, logs);
  p := r.p; rep := r.rep; logs := r.logs;
  if not game.can_reach(p, p_x, p_y) then perform game.save(p); return game.respond(p.id, false, 'too_fast', rep, logs); end if;
  select * into l from public.links where id = p_link;
  if l.id is null then perform game.save(p); return game.respond(p.id, false, 'no_such_link', rep, logs); end if;
  if greatest(abs(p_x - l.at_x), abs(p_y - l.at_y)) > 1 then perform game.save(p); return game.respond(p.id, false, 'not_at_link', rep, logs); end if;
  if p.stunned_until > now() then perform game.save(p); return game.respond(p.id, false, 'stunned', rep, logs); end if;
  -- Climbing ends whatever you were doing here, like walking away does.
  if p.fight_enemy is not null then
    update public.enemies set fighter = null where id = p.fight_enemy and fighter = p.id;
    p.fight_enemy := null;
  end if;
  p.job_crime := null; p.job_spot := null; p.job_started_at := null; p.job_ends_at := null;
  p.cook_item := null; p.cook_next := null;
  p.pos_x := l.to_x; p.pos_y := l.to_y; p.pos_at := now();
  insert into public.walks (player_id, from_x, from_y, path, started_at) values (p.id, l.to_x, l.to_y, '[]'::jsonb, now())
  on conflict (player_id) do update set from_x = excluded.from_x, from_y = excluded.from_y, path = excluded.path, started_at = excluded.started_at;
  perform game.save(p);
  return game.respond(p.id, true, null, rep, logs);
end $$;
grant execute on function public.climb(text, int, int) to authenticated;
revoke execute on function public.climb(text, int, int) from public, anon;

-- ---------- rat meat ----------
insert into public.items (id, name, slot, damage, accuracy, defence, speed, needs_skill, needs_level, heal, value) values
  ('raw_rat_meat', '${raw.name}', null, 0, 0, 0, null, null, 1, ${raw.heal}, ${raw.value}),
  ('cooked_rat_meat', '${cooked.name}', null, 0, 0, 0, null, null, 1, ${cooked.heal}, ${cooked.value})
on conflict (id) do update set name = excluded.name, heal = excluded.heal, value = excluded.value;
insert into public.recipes (item_from, item_to, station_kind, level, xp, stop_burn_level)
values ('${rc.from}', '${rc.to}', '${rc.station}', ${rc.level}, ${rc.xp}, ${rc.stopBurn})
on conflict (item_from) do update set item_to = excluded.item_to, station_kind = excluded.station_kind, level = excluded.level,
  xp = excluded.xp, stop_burn_level = excluded.stop_burn_level;

-- ---------- the rats ----------
insert into public.enemy_kinds (id, name, level, hp, attack, defense, defence_bonus, speed, max_hit, respawn, aggressive)
values ('rat', '${k.name}', ${k.level}, ${k.hp}, ${k.attack}, ${k.defense}, ${k.defenceBonus}, ${k.speed}, ${k.maxHit}, ${k.respawn}, ${k.aggressive})
on conflict (id) do update set name = excluded.name, level = excluded.level, hp = excluded.hp, attack = excluded.attack, defense = excluded.defense,
  defence_bonus = excluded.defence_bonus, speed = excluded.speed, max_hit = excluded.max_hit, respawn = excluded.respawn, aggressive = excluded.aggressive;
insert into public.enemies (id, kind, idx, hp) values
${rats.map((t) => `  ('${t.id}', 'rat', ${t.index}, ${k.hp})`).join(',\n')}
on conflict (id) do nothing;
insert into public.loot (enemy_kind, item, chance, min_amount, max_amount)
select 'rat', 'raw_rat_meat', 1, 1, 1 where not exists (select 1 from public.loot where enemy_kind = 'rat' and item = 'raw_rat_meat');

-- Where rat idx is at time t (ms): the same schedule as ratAt() in the game. Its patch is tiles zs[idx+1] .. +zn[idx+1]-1.
create or replace function game.rat_at(idx int, t bigint, out x double precision, out z double precision, out flying boolean)
language plpgsql immutable set search_path = pg_catalog, game as $$
declare
  px int[] := array[${tiles.map((p) => p[0]).join(',')}];
  py int[] := array[${tiles.map((p) => p[1]).join(',')}];
  zs int[] := array[${starts.join(',')}];
  zn int[] := array[${RAT_ZONES.map((z) => z.length).join(',')}];
  shifted bigint := t + idx * 3331;
  k bigint := shifted / ${RAT_MOVE_MS};
  into_move bigint := shifted - k * ${RAT_MOVE_MS};
  a int;
  b int;
  f double precision;
begin
  flying := false;
  a := zs[idx + 1] + (game.minstd(((k * 3 + idx) % 2147483647) + 1) % zn[idx + 1])::int;
  if into_move >= ${RAT_WALK_MS} then
    x := px[a] + 0.5; z := py[a] + 0.5;
    return;
  end if;
  b := zs[idx + 1] + (game.minstd((((k - 1) * 3 + idx) % 2147483647) + 1) % zn[idx + 1])::int;
  f := into_move / ${RAT_WALK_MS}.0;
  x := px[b] + 0.5 + (px[a] - px[b]) * f;
  z := py[b] + 0.5 + (py[a] - py[b]) * f;
end $$;
revoke execute on function game.rat_at(int, bigint) from public, anon, authenticated;

-- Where an enemy of this kind is (each kind has its own schedule).
create or replace function game.enemy_at(p_kind text, idx int, t bigint, out x double precision, out z double precision, out flying boolean)
language plpgsql immutable set search_path = pg_catalog, game as $$
begin
  if p_kind = 'thug' then
    select * into x, z, flying from game.thug_at(idx, t);
  elsif p_kind = 'rat' then
    select * into x, z, flying from game.rat_at(idx, t);
  else
    select * into x, z, flying from game.pigeon_at(idx, t);
  end if;
end $$;
revoke execute on function game.enemy_at(text, int, bigint) from public, anon, authenticated;

-- Check: this should say "ok".
select case when game.on_map(${SEWER.x0}, ${SEWER.y0}) and position('game.on_map' in pg_get_functiondef('public.walk(integer, integer, jsonb)'::regprocedure)) > 0
  and (select count(*) from public.enemies where kind = 'rat') = ${rats.length} then 'ok' else 'NOT APPLIED' end as sewer;
`;
writeFileSync(new URL('../supabase/migrations/0019_sewer.sql', import.meta.url), sql);
console.log(`wrote 0019_sewer.sql (${sql.length} bytes, ${tiles.length} rat tiles)`);
